using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared.RCD;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.RCD;

/// <summary>
/// The RPD's own radial menu: the usual RCD mode radial with an always-visible strip of
/// pipe colours pinned along the bottom.
/// </summary>
/// <remarks>
/// Palmtree: ported from the old Coyote code.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class RPDMenu : RadialMenu
{
    [Dependency] private readonly ILocalizationManager _locManager = default!;

    private readonly RCDMenu _rcdMenu;

    private string? _selectedColor;

    public event Action<string>? ColorSelected;

    public event Action<ProtoId<RCDPrototype>>? SendRCDSystemMessageAction
    {
        add => _rcdMenu.SendRCDSystemMessageAction += value;
        remove => _rcdMenu.SendRCDSystemMessageAction -= value;
    }

    public RPDMenu()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _rcdMenu = new RCDMenu();

        if (FindControl<Control>("RCDMenuHolder") is { } rcdHolder)
        {
            rcdHolder.AddChild(_rcdMenu);
            _rcdMenu.OnClose += Close;
        }
    }

    public void SetEntity(EntityUid uid)
    {
        _rcdMenu.SetEntity(uid);
    }

    /// <summary>
    /// Fills in the colour strip. <paramref name="palette"/> maps palette key to colour, where a
    /// null colour is the "no paint" default entry.
    /// </summary>
    public void Populate(Dictionary<string, Color?> palette, string selectedColor = "default")
    {
        _selectedColor = palette.ContainsKey(selectedColor) ? selectedColor : "default";

        var colorList = FindControl<BoxContainer>("ColorList");

        if (colorList == null)
            return;

        colorList.RemoveAllChildren();

        foreach (var color in palette)
        {
            var button = new Button
            {
                Name = $"ColorBox_{color.Key}",
                Visible = true,
                MinSize = new Vector2(30, 30),
                MaxSize = new Vector2(30, 30),
                Margin = new Thickness(6),
                StyleClasses = { "OpenBoth" },
                ToolTip = _locManager.GetString($"rpd-color-{color.Key}"),
            };

            var colorPanel = new PanelContainer
            {
                MinSize = new Vector2(30, 30),
                MaxSize = new Vector2(30, 30),
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = color.Value ?? Color.Transparent,
                },
            };

            UpdateButtonBorder(colorPanel, color.Key);

            button.OnMouseEntered += _ =>
            {
                if (colorPanel.PanelOverride is not StyleBoxFlat styleBox)
                    return;

                // The default entry is transparent, so give it a visible hover outline anyway
                if (color.Value == null)
                    styleBox.BackgroundColor = new Color(255, 255, 255, 40);

                styleBox.BorderColor = Color.LightBlue;
                styleBox.BorderThickness = new Thickness(3);
            };

            button.OnMouseExited += _ =>
            {
                if (colorPanel.PanelOverride is StyleBoxFlat styleBox && color.Value == null)
                    styleBox.BackgroundColor = Color.Transparent;

                UpdateButtonBorder(colorPanel, color.Key);
            };

            button.OnPressed += _ =>
            {
                if (_selectedColor == color.Key)
                    return;

                _selectedColor = color.Key;
                UpdateAllButtonBorders();
                ColorSelected?.Invoke(color.Key);
            };

            button.AddChild(colorPanel);
            colorList.AddChild(button);
        }

        UpdateAllButtonBorders();
    }

    private void UpdateButtonBorder(PanelContainer panel, string colorKey)
    {
        if (panel.PanelOverride is not StyleBoxFlat styleBox)
            return;

        styleBox.BorderColor = _selectedColor == colorKey ? Color.Gold : Color.Transparent;
        styleBox.BorderThickness = new Thickness(3);
    }

    private void UpdateAllButtonBorders()
    {
        var colorList = FindControl<BoxContainer>("ColorList");

        if (colorList == null)
            return;

        foreach (var child in colorList.Children)
        {
            if (child is not Button button || button.Name == null)
                continue;

            string colorKey;

            if (button.Name == "DefaultButton")
                colorKey = "default";
            else if (button.Name.StartsWith("ColorBox_"))
                colorKey = button.Name.Replace("ColorBox_", "");
            else
                continue;

            if (button.Children.OfType<PanelContainer>().FirstOrDefault() is { } panel)
                UpdateButtonBorder(panel, colorKey);
        }
    }
}
