/// <summary>
///     The stormdrive control console, laid out like NSV13's <c>StormdriveConsole.js</c>: the AZ-1
///     to AZ-7 preset column, the rod slider, the six statistics bars and the fuel-line composition
///     with its graph.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class StormdriveConsoleWindow : DefaultWindow
{
    public event Action<float>? OnSetRods;
    public event Action<int>? OnPreset;
    public event Action? OnToggleMaintenance;
    public event Action? OnToggleDump;

    // tgui colours, so the bars match StormdriveConsole.js.
    private static readonly Color Red = Color.FromHex("#DB2828");
    private static readonly Color Amber = Color.FromHex("#FBBD08");
    private static readonly Color Green = Color.FromHex("#21BA45");
    private static readonly Color Grey = Color.FromHex("#767676");

    private static readonly StyleBoxFlat RedFill = Fill(Red);
    private static readonly StyleBoxFlat AmberFill = Fill(Amber);
    private static readonly StyleBoxFlat GreenFill = Fill(Green);
    private static readonly StyleBoxFlat GreyFill = Fill(Grey);

    /// <summary>
    ///     Composition row colours, in <see cref="StormdriveConsoleGas"/> order. Values come straight
    ///     from StormdriveConsole.js so the graph and the bars agree with the original.
    /// </summary>
    private static readonly Color[] GasColours =
    {
        Color.FromHex("#6435C9"), // constricted plasma
        Color.FromHex("#A333C8"), // plasma
        Color.FromHex("#E03997"), // tritium
        Color.FromHex("#2185D0"), // oxygen
        Color.FromHex("#FF0000"), // nitrogen
        Color.FromHex("#767676"), // carbon dioxide
        Color.FromHex("#FFFFFF"), // water vapour
        Color.FromHex("#00B5AD"), // hyper-noblium
        Color.FromHex("#7E90A7"), // nitrous oxide
        Color.FromHex("#425770"), // nitryl
        Color.FromHex("#F2711C"), // bz
        Color.FromHex("#FBD608"), // stimulum
        Color.FromHex("#B5CC18"), // pluoxium
        Color.FromHex("#A5673F"), // nucleium
    };

    private readonly Label[] _gasLabels = new Label[(int) StormdriveConsoleGas.Count];
    private readonly ProgressBar[] _gasBars = new ProgressBar[(int) StormdriveConsoleGas.Count];

    private StormdriveConsoleBoundUserInterfaceState? _state;

    public StormdriveConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        RodSlider.MinValue = 0f;
        RodSlider.MaxValue = 100f;

        // Commit on release only. The physics tick is 2 s; streaming every intermediate value would
        // just hammer the setpoint (and, faithfully, wear the rods - DM's own slider did the same).
        // OnReleased already fires on the same click release, so an OnKeyBindUp handler here would
        // send the setpoint twice and charge the rods twice for one drag.
        RodSlider.OnReleased += range =>
        {
            if (_state is { HasReactor: true })
                OnSetRods?.Invoke(range.Value);
        };

        Preset1.OnPressed += _ => Preset(0);
        Preset2.OnPressed += _ => Preset(1);
        Preset3.OnPressed += _ => Preset(2);
        Preset4.OnPressed += _ => Preset(3);
        Preset5.OnPressed += _ => Preset(4);

        MaintenanceButton.OnPressed += _ => OnToggleMaintenance?.Invoke();
        DumpButton.OnPressed += _ => OnToggleDump?.Invoke();

        StabilityHelp.TooltipSupplier = _ => BuildStabilityTooltip();

        BuildGasRows();
    }

    /// <summary>
    ///     Wrapped rich-text tooltip for the stability "?" button.
    /// </summary>
    /// <remarks>
    ///     A plain <see cref="Control.Tooltip"/> is measured against an unbounded width, so a
    ///     paragraph becomes one very long line. Pinning the label's width is what makes the
    ///     explanation readable.
    /// </remarks>
    private static Tooltip BuildStabilityTooltip()
    {
        var label = new RichTextLabel
        {
            SetWidth = 420f,
        };
        label.SetMarkup(Loc.GetString("stormdrive-console-stability-tooltip"));

        var tooltip = new Tooltip();
        tooltip.GetChild(0).Children.Clear();
        tooltip.GetChild(0).Children.Add(label);
        return tooltip;
    }

    private static StyleBoxFlat Fill(Color color) => new() { BackgroundColor = color };

    private void BuildGasRows()
    {
        for (var i = 0; i < (int) StormdriveConsoleGas.Count; i++)
        {
            var label = new Label
            {
                Text = Loc.GetString($"stormdrive-console-gas-{(StormdriveConsoleGas) i}"),
                HorizontalExpand = true,
            };

            var bar = new ProgressBar
            {
                MinValue = 0f,
                MaxValue = 1f,
                SetWidth = 200f,
                SetHeight = 18f,
            };

            bar.ForegroundStyleBoxOverride = Fill(GasColours[i]);

            _gasLabels[i] = label;
            _gasBars[i] = bar;

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
            };

            row.AddChild(label);
            row.AddChild(bar);
            GasList.AddChild(row);
        }
    }

    private void Preset(int index)
    {
        if (_state is not { HasReactor: true })
            return;

        OnPreset?.Invoke(index);
    }

    public void UpdateState(StormdriveConsoleBoundUserInterfaceState state)
    {
        _state = state;

        if (!state.HasReactor)
        {
            StatusLabel.Text = Loc.GetString("stormdrive-console-no-reactor");
            GasChart.Clear();
            return;
        }

        var status = state.State switch
        {
            StormdriveConsoleState.Maintenance => Loc.GetString("stormdrive-console-status-maintenance"),
            StormdriveConsoleState.Idle => Loc.GetString("stormdrive-console-status-idle"),
            StormdriveConsoleState.Running => Loc.GetString("stormdrive-console-status-running"),
            StormdriveConsoleState.Meltdown => Loc.GetString("stormdrive-console-status-meltdown"),
            StormdriveConsoleState.Repair => Loc.GetString("stormdrive-console-status-repair"),
            StormdriveConsoleState.Reinforce => Loc.GetString("stormdrive-console-status-reinforce"),
            StormdriveConsoleState.Refit => Loc.GetString("stormdrive-console-status-refit"),
            _ => Loc.GetString("stormdrive-console-status-idle"),
        };

        var statusColour = state.State switch
        {
            StormdriveConsoleState.Meltdown => Red,
            StormdriveConsoleState.Running => Amber,
            _ => Grey,
        };

        // "Fission reaction stable" is a lie when the core is above the critical line or the
        // meltdown fuse is already burning. Escalate the banner with the same thresholds the
        // simulation uses, so the console cannot look calm while the core is cooking.
        //
        // The near-meltdown tier exists because "MELTDOWN IMMINENT" at the critical line (650 °C)
        // is 150 °C of headroom away from the 800 °C fuse - a load of noise for a core that is
        // merely hot. Reserve that wording for the last tenth of the band; below it, say what is
        // actually true and what to do.
        if (state.State == StormdriveConsoleState.Running)
        {
            if (state.MeltdownCountdown > 0f)
            {
                status = Loc.GetString("stormdrive-console-status-destabilised");
                statusColour = Red;
            }
            else if (state.TemperatureMeltdown > 0f && state.Heat > state.TemperatureMeltdown * 0.9f)
            {
                status = Loc.GetString("stormdrive-console-status-near-meltdown");
                statusColour = Red;
            }
            else if (state.Heat > state.TemperatureCritical)
            {
                status = Loc.GetString("stormdrive-console-status-overheat");
                statusColour = Red;
            }
            else if (state.Heat > state.TemperatureHot)
            {
                status = Loc.GetString("stormdrive-console-status-hot");
                statusColour = Amber;
            }
        }

        StatusLabel.Text = status;
        StatusLabel.FontColorOverride = statusColour;

        MessageLabel.Text = state.Notice;
        UpdateStatistics(state);
        UpdateComposition(state);

        // Do not fight the engineer while they are dragging. The slider never takes keyboard focus,
        // so Grabbed is the only reliable "the mouse is down on it" signal; without this the
        // half-second refresh snapped the handle back to the server value mid-drag.
        if (!RodSlider.Grabbed)
            RodSlider.SetValueWithoutEvent(state.RodPercent);

        RodPercentLabel.Text = Loc.GetString("stormdrive-console-percent-value", ("value", $"{state.RodPercent:F1}"));

        MaintenanceButton.Text = state.Maintenance
            ? Loc.GetString("stormdrive-console-maintenance-off")
            : Loc.GetString("stormdrive-console-maintenance");

        // DM: maintenance can only be engaged from idle, so the button is dead in every other state.
        MaintenanceButton.Disabled = !state.Maintenance && state.State != StormdriveConsoleState.Idle;

        DumpButton.Text = state.PipeOpen
            ? Loc.GetString("stormdrive-console-dump-open")
            : Loc.GetString("stormdrive-console-dump");

        DumpButton.Disabled = state.State is StormdriveConsoleState.Maintenance
            or StormdriveConsoleState.Meltdown;

        // SCRAM is always available while there is a core to shut down.
        Preset5.Disabled = state.State is StormdriveConsoleState.Maintenance or StormdriveConsoleState.Meltdown;
    }

    private void UpdateStatistics(StormdriveConsoleBoundUserInterfaceState state)
    {
        // Temperature: good below hot, average to critical, bad past critical (StormdriveConsole.js
        // maps the bar against reactor_meltdown).
        var heatFraction = state.TemperatureMeltdown <= 0f
            ? 0f
            : Math.Clamp(state.Heat / state.TemperatureMeltdown, 0f, 1f);

        HeatBar.Value = heatFraction;
        HeatBar.ForegroundStyleBoxOverride = state.Heat >= state.TemperatureCritical ? RedFill
            : state.Heat >= state.TemperatureHot ? AmberFill : GreenFill;
        HeatLabel.Text = Loc.GetString("stormdrive-console-heat-value", ("value", $"{state.Heat:F0}"));

        UpdateStability(state);

        // Rod integrity: good above 66 %, average to 33 %, bad below.
        var integrity = Math.Clamp(state.RodIntegrity / 100f, 0f, 1f);
        RodIntegrityBar.Value = integrity;
        RodIntegrityBar.ForegroundStyleBoxOverride = integrity >= 0.66f ? GreenFill
            : integrity >= 0.33f ? AmberFill : RedFill;
        RodIntegrityLabel.Text = Loc.GetString("stormdrive-console-percent-value", ("value", $"{state.RodIntegrity:F0}"));

        // Power output: the JS bar is "at least 8 % of rated is good", inverted.
        var theoretical = MathF.Max(state.TheoreticalMaximumPower, 1f);
        var power = Math.Clamp(state.LastPowerProduced / theoretical, 0f, 1f);
        PowerBar.Value = power;
        PowerBar.ForegroundStyleBoxOverride = power >= 0.20f ? GreenFill
            : power >= 0.08f ? AmberFill : RedFill;
        PowerLabel.Text = Loc.GetString("stormdrive-console-power-value",
            ("value", $"{state.LastPowerProduced / 1e6:F2}"),
            ("max", $"{state.TheoreticalMaximumPower / 1e6:F2}"));

        // Reaction rate, in mol/s. The drive's internal figure is moles per two-second tick, so the
        // 10 mol/s full-scale bar keeps the old green/amber cut-offs (2 and 1 moles per tick, i.e.
        // 1.0 and 0.5 mol/s when the tick is converted).
        ReactionBar.Value = Math.Clamp(state.ReactionRate * 0.1f, 0f, 1f);
        ReactionBar.ForegroundStyleBoxOverride = state.ReactionRate >= 1.0f ? GreenFill
            : state.ReactionRate >= 0.5f ? AmberFill : RedFill;
        ReactionRateLabel.Text = Loc.GetString("stormdrive-console-reaction-value", ("value", $"{state.ReactionRate:F1}"));

        // Fuel ratio: a lean mixture is the dangerous one - below 12.5 % the reaction starves.
        // The comparison matches the simulation's strict boundaries, so a mixture sitting exactly
        // on 12.5 % or 25 % is coloured for the branch it will actually take.
        var ratio = state.TotalMoles <= 0f ? 0f : Math.Clamp(state.FuelMix / state.TotalMoles, 0f, 1f);
        FuelRatioBar.Value = ratio;
        FuelRatioBar.ForegroundStyleBoxOverride = ratio < 0.125f ? RedFill
            : ratio < 0.25f ? AmberFill : GreenFill;
        FuelRatioLabel.Text = Loc.GetString("stormdrive-console-percent-value", ("value", $"{ratio * 100f:F0}"));

        // Fuel moles: plotted against the "very high" band. The over-pressure branch is strict (the
        // line only bleeds when total moles are *above* rate * 12 + 20), so equality stays green.
        var veryHigh = MathF.Max(state.MoleThresholdVeryHigh, 1f);
        var moles = Math.Clamp(state.TotalMoles / veryHigh, 0f, 1f);
        FuelMolesBar.Value = moles;
        FuelMolesBar.ForegroundStyleBoxOverride = state.TotalMoles > state.MoleThresholdVeryHigh ? RedFill
            : state.TotalMoles > state.MoleThresholdHigh ? AmberFill : GreenFill;
        FuelMolesLabel.Text = Loc.GetString("stormdrive-console-moles-value", ("value", $"{state.TotalMoles:F0}"));

        // Armed meltdown: the fuse gets its own banner, with the count in it, instead of a stray
        // label at the bottom of the statistics list. Hidden entirely when nothing is burning.
        var armed = state.MeltdownCountdown > 0f && state.MeltdownDelay > 0f;
        MeltdownPanel.Visible = armed;

        if (armed)
        {
            CountdownLabel.Text = Loc.GetString("stormdrive-console-countdown-value",
                ("seconds", $"{state.MeltdownCountdown:F0}"));

            // Drains as the fuse burns; a bar is far easier to read at a glance than a number.
            MeltdownBar.Value = Math.Clamp(1f - state.MeltdownCountdown / state.MeltdownDelay, 0f, 1f);
            MeltdownBar.ForegroundStyleBoxOverride = RedFill;
        }
    }

    /// <summary>
    ///     Draw the stability bar and its diagnosis line.
    /// </summary>
    private void UpdateStability(StormdriveConsoleBoundUserInterfaceState state)
    {
        var stability = Math.Clamp(state.ReactorStability, 0f, 100f);
        StabilityBar.Value = stability;
        // The simulation's spike/anomaly rolls are strict "< threshold" checks, so exactly 75 is
        // still safe and exactly 15 has not started rolling anomalies yet.
        StabilityBar.ForegroundStyleBoxOverride = stability >= state.StabilitySpikeThreshold ? GreenFill
            : stability >= state.StabilityAnomalyThreshold ? AmberFill
            : RedFill;
        StabilityLabel.Text = Loc.GetString("stormdrive-console-percent-value", ("value", $"{stability:F0}"));

        UpdateStabilityDiagnosis(state);
    }

    /// <summary>
    ///     Name the fuel-line condition responsible for the current stability movement.
    /// </summary>
    /// <remarks>
    ///     Mirrors the RBMK integrity diagnosis: the bar alone is not actionable. Each case names
    ///     the fix (raise the ratio, lower the input pressure, refuel, lower output).
    /// </remarks>
    private void UpdateStabilityDiagnosis(StormdriveConsoleBoundUserInterfaceState state)
    {
        if (state.State != StormdriveConsoleState.Running)
        {
            StabilityDiagnosisLabel.Text = string.Empty;
            StabilityDiagnosisLabel.FontColorOverride = null;
            return;
        }

        var rate = MathF.Abs(state.StabilityDelta);

        switch (state.StabilityCause)
        {
            case StormdriveStabilityCause.Recovering:
                StabilityDiagnosisLabel.Text = Loc.GetString("stormdrive-console-stability-recovering",
                    ("rate", $"{rate:F2}"));
                StabilityDiagnosisLabel.FontColorOverride = Green;
                break;

            case StormdriveStabilityCause.RichOverpressure:
                StabilityDiagnosisLabel.Text = Loc.GetString("stormdrive-console-stability-rich-overpressure",
                    ("rate", $"{rate:F2}"));
                StabilityDiagnosisLabel.FontColorOverride = Amber;
                break;

            case StormdriveStabilityCause.Lean:
                StabilityDiagnosisLabel.Text = Loc.GetString("stormdrive-console-stability-lean",
                    ("rate", $"{rate:F2}"));
                StabilityDiagnosisLabel.FontColorOverride = Amber;
                break;

            case StormdriveStabilityCause.LeanOverpressure:
                StabilityDiagnosisLabel.Text = Loc.GetString("stormdrive-console-stability-lean-overpressure",
                    ("rate", $"{rate:F2}"));
                StabilityDiagnosisLabel.FontColorOverride = Red;
                break;

            case StormdriveStabilityCause.Starved:
                StabilityDiagnosisLabel.Text = Loc.GetString("stormdrive-console-stability-starved",
                    ("rate", $"{rate:F2}"));
                StabilityDiagnosisLabel.FontColorOverride = Red;
                break;

            case StormdriveStabilityCause.Overload:
                StabilityDiagnosisLabel.Text = Loc.GetString("stormdrive-console-stability-overload",
                    ("rate", $"{rate:F2}"));
                StabilityDiagnosisLabel.FontColorOverride = Red;
                break;

            case StormdriveStabilityCause.Anomaly:
                StabilityDiagnosisLabel.Text = Loc.GetString("stormdrive-console-stability-anomaly");
                StabilityDiagnosisLabel.FontColorOverride = Red;
                break;

            default:
                StabilityDiagnosisLabel.Text = state.ReactorStability >= 99.5f
                    ? Loc.GetString("stormdrive-console-stability-holding")
                    : Loc.GetString("stormdrive-console-stability-steady");
                StabilityDiagnosisLabel.FontColorOverride = state.ReactorStability >= 99.5f ? Green : null;
                break;
        }
    }

    private void UpdateComposition(StormdriveConsoleBoundUserInterfaceState state)
    {
        var total = MathF.Max(state.TotalMoles, 0.0001f);
        var values = new[]
        {
            state.ConstrictedPlasma,
            state.Plasma,
            state.Tritium,
            state.Oxygen,
            state.Nitrogen,
            state.CarbonDioxide,
            state.WaterVapor,
            state.HyperNoblium,
            state.NitrousOxide,
            state.Nitryl,
            state.BZ,
            state.Stimulum,
            state.Pluoxium,
            state.Nucleium,
        };

        for (var i = 0; i < values.Length && i < _gasBars.Length; i++)
        {
            var fraction = Math.Clamp(values[i] / total, 0f, 1f);
            _gasBars[i].Value = fraction;
            _gasLabels[i].Text = Loc.GetString($"stormdrive-console-gas-{(StormdriveConsoleGas) i}",
                ("percent", $"{fraction * 100f:F1}"));
        }

        TotalMolesLabel.Text = Loc.GetString("stormdrive-console-moles-value", ("value", $"{state.TotalMoles:F0}"));

        var series = new List<ReactorChart.ChartSeries>(Math.Min(state.GasHistory.Count, values.Length));

        for (var i = 0; i < state.GasHistory.Count && i < values.Length; i++)
        {
            series.Add(new ReactorChart.ChartSeries
            {
                Values = state.GasHistory[i].ToArray(),
                Min = 0f,
                Max = 100f,
                Colour = GasColours[i],
            });
        }

        GasChart.SetSeries(series);
    }
}
