using Content.Shared._NSV13.Reactor;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NSV13.Reactor.UI;

/// <summary>
///     Rod bay window, laid out like NSV13's <c>StormdriveControlRods.js</c>: one bordered section
///     per mounted rod, carrying its name, an eject button and an integrity bar.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class StormdriveRodsWindow : DefaultWindow
{
    public event Action<int>? OnRemoveRod;

    private static readonly Color Red = Color.FromHex("#DB2828");
    private static readonly Color Amber = Color.FromHex("#FBBD08");
    private static readonly Color Green = Color.FromHex("#21BA45");

    private static readonly StyleBoxFlat RedFill = new() { BackgroundColor = Red };
    private static readonly StyleBoxFlat AmberFill = new() { BackgroundColor = Amber };
    private static readonly StyleBoxFlat GreenFill = new() { BackgroundColor = Green };

    public StormdriveRodsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateState(StormdriveRodsBoundUserInterfaceState state)
    {
        StatusLabel.Text = state.Broken
            ? Loc.GetString("stormdrive-rods-broken")
            : state.Maintenance
                ? Loc.GetString("stormdrive-rods-open")
                : Loc.GetString("stormdrive-rods-closed");

        StatusLabel.FontColorOverride = state.Broken ? Red : state.Maintenance ? Green : null;

        MessageLabel.Text = state.Notice;

        RodList.RemoveAllChildren();

        if (state.Rods.Count == 0)
        {
            RodList.AddChild(new Label { Text = Loc.GetString("stormdrive-rods-empty") });
            return;
        }

        for (var i = 0; i < state.Rods.Count; i++)
        {
            var rod = state.Rods[i];
            var index = i;

            var panel = new PanelContainer { HorizontalExpand = true };
            panel.AddStyleClass("Inset");

            var section = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 4,
                Margin = new Thickness(6),
            };

            section.AddChild(new Label
            {
                Text = rod.Name,
                StyleClasses = { "LabelHeading" },
            });

            var eject = new Button
            {
                Text = Loc.GetString("stormdrive-rods-eject-name", ("name", rod.Name)),
                HorizontalExpand = true,
                // The server, not the window, is the authority on when a rod may be pulled: it
                // allows a running core (at a cost) and refuses an idle one with a notice.
                Disabled = state.Broken,
            };

            eject.OnPressed += _ => OnRemoveRod?.Invoke(index);
            section.AddChild(eject);

            var integrity = Math.Clamp(rod.Percent / 100f, 0f, 1f);
            var bar = new ProgressBar
            {
                MinValue = 0f,
                MaxValue = 1f,
                Value = integrity,
                SetHeight = 20f,
                HorizontalExpand = true,
            };

            // StormdriveControlRods.js: good above 66 %, average down to 33 %, bad below.
            bar.ForegroundStyleBoxOverride = integrity >= 0.66f ? GreenFill
                : integrity >= 0.33f ? AmberFill : RedFill;

            section.AddChild(bar);

            section.AddChild(new Label
            {
                Text = Loc.GetString("stormdrive-rods-entry",
                    ("name", rod.Name),
                    ("percent", $"{rod.Percent:F0}"),
                    ("effectiveness", $"{rod.Effectiveness:F1}")),
                StyleClasses = { "LabelSubText" },
            });

            panel.AddChild(section);
            RodList.AddChild(panel);
        }
    }
}
