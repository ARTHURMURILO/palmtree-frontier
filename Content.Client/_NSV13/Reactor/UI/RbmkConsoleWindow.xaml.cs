using Content.Shared._NSV13.Reactor;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;

namespace Content.Client._NSV13.Reactor.UI;

/// <summary>
///     RBMK console window, laid out like the three NSV13 reactor computers.
/// </summary>
/// <remarks>
///     NSV13 ships the reactor controls as separate tgui windows: <c>RbmkControlRods</c> (setpoint),
///     <c>RbmkStats</c> (legend + history graphs) and the fuel management console. They are folded
///     into one window here - the port has a single console machine - but each tab reproduces its
///     original window: same bars, same ranges, same colours, same readouts.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class RbmkConsoleWindow : DefaultWindow
{
    /// <summary>Emitted when the engineer commits a new rod setpoint.</summary>
    public event Action<float>? OnSetTarget;

    /// <summary>Emitted with the index of the fuel rod to pull.</summary>
    public event Action<int>? OnEjectRod;

    private const float MaxTarget = 3f;
    private const float MinTarget = 0f;

    // tgui's named colours, so the bars read the same as the originals.
    private static readonly Color Yellow = Color.FromHex("#FFD700");
    private static readonly Color White = Color.FromHex("#FFFFFF");
    private static readonly Color Blue = Color.FromHex("#2185D0");
    private static readonly Color Red = Color.FromHex("#DB2828");
    private static readonly Color Green = Color.FromHex("#21BA45");
    private static readonly Color Amber = Color.FromHex("#FBBD08");
    private static readonly Color Grey = Color.FromHex("#767676");

    private static readonly StyleBoxFlat YellowFill = Fill(Yellow);
    private static readonly StyleBoxFlat WhiteFill = Fill(White);
    private static readonly StyleBoxFlat BlueFill = Fill(Blue);
    private static readonly StyleBoxFlat RedFill = Fill(Red);
    private static readonly StyleBoxFlat GreenFill = Fill(Green);
    private static readonly StyleBoxFlat AmberFill = Fill(Amber);
    private static readonly StyleBoxFlat GreyFill = Fill(Grey);

    private RbmkConsoleBoundUserInterfaceState? _state;

    /// <summary>
    ///     True while the engineer is dragging the setpoint slider.
    /// </summary>
    /// <remarks>
    ///     The window refreshes twice a second. Letting that refresh write the server's setpoint
    ///     back into the slider and the insertion bar while the mouse is down made the bar flicker
    ///     between the dragged value and the last acknowledged one.
    /// </remarks>
    private bool _dragging;

    public RbmkConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Tabs.SetTabTitle(0, Loc.GetString("rbmk-console-tab-rods"));
        Tabs.SetTabTitle(1, Loc.GetString("rbmk-console-tab-stats"));
        Tabs.SetTabTitle(2, Loc.GetString("rbmk-console-tab-fuel"));

        RodSlider.MinValue = MinTarget;
        RodSlider.MaxValue = MaxTarget;

        RodSlider.OnGrabbed += _ => _dragging = true;

        RodSlider.OnValueChanged += range =>
        {
            // The DM console's slider was a 0..3 float with a 0.1 step.
            var value = MathF.Round(range.Value * 10f) / 10f;
            UpdateTargetReadout(value);
        };

        // Only commit on release: the physics tick is 2 s, so streaming every intermediate value
        // would just spam the setpoint.
        RodSlider.OnKeyBindUp += args =>
        {
            if (args.Function == EngineKeyFunctions.UIClick)
                Commit(MathF.Round(RodSlider.Value * 10f) / 10f);
        };

        // Keyboard/wheel adjustments never fire OnKeyBindUp.
        RodSlider.OnReleased += range =>
        {
            _dragging = false;
            Commit(MathF.Round(range.Value * 10f) / 10f);
        };
    }

    private static StyleBoxFlat Fill(Color color) => new() { BackgroundColor = color };

    private void Commit(float value)
    {
        if (_state is not { HasReactor: true })
            return;

        OnSetTarget?.Invoke(Math.Clamp(value, MinTarget, MaxTarget));
    }

    private void UpdateTargetReadout(float value)
    {
        var insertion = Math.Clamp(1f - value / MaxTarget, 0f, 1f);

        TargetText.Text = Loc.GetString("rbmk-console-target-value", ("value", $"{value:F1}"));
        InsertionText.Text = Loc.GetString("rbmk-console-rod-insertion-value",
            ("percent", $"{insertion * 100f:F0}"));

        InsertionBar.Value = insertion;
        InsertionBar.ForegroundStyleBoxOverride = insertion >= 0.7f ? GreenFill
            : insertion >= 0.4f ? AmberFill : RedFill;
    }

    public void UpdateState(RbmkConsoleBoundUserInterfaceState state)
    {
        _state = state;

        if (!state.HasReactor)
        {
            StatusLabel.Text = Loc.GetString("rbmk-console-no-reactor");
            StatsChart.Clear();
            return;
        }

        StatusLabel.Text = state.Slagged
            ? Loc.GetString("rbmk-console-status-slagged")
            : state.Running
                ? Loc.GetString("rbmk-console-status-running")
                : Loc.GetString("rbmk-console-status-idle");

        StatusLabel.FontColorOverride = state.Slagged
            ? Red
            : state.Running
                ? Amber
                : Grey;

        UpdateRodsTab(state);
        UpdateStatsTab(state);
        UpdateFuelTab(state);

        MessageLabel.Text = state.Notice;
    }

    private void UpdateRodsTab(RbmkConsoleBoundUserInterfaceState state)
    {
        var k = Math.Clamp(state.K / MathF.Max(MaxTarget, 0.01f), 0f, 1f);
        KBar.Value = k;
        KBar.ForegroundStyleBoxOverride = k <= 0.4f ? GreenFill
            : k <= 0.6f ? AmberFill : RedFill;
        KText.Text = Loc.GetString("rbmk-console-reactivity-value", ("k", $"{state.K:F2}"));

        // Do not fight the engineer while they are dragging: the drag handler keeps the readouts
        // in sync with the slider, and the next server state takes over again on release.
        if (!_dragging && !RodSlider.HasKeyboardFocus())
        {
            RodSlider.SetValueWithoutEvent(Math.Clamp(state.DesiredK, MinTarget, MaxTarget));
            UpdateTargetReadout(state.DesiredK);
        }
    }

    private void UpdateStatsTab(RbmkConsoleBoundUserInterfaceState state)
    {
        PowerBar.Value = Math.Clamp(state.Power, 0f, 100f);
        PowerBar.ForegroundStyleBoxOverride = YellowFill;
        PowerText.Text = Loc.GetString("rbmk-console-power-value", ("value", $"{state.Power:F1}"));

        PressureBar.Value = Math.Clamp(state.Pressure, 0f, 2000f);
        PressureBar.ForegroundStyleBoxOverride = state.Pressure >= state.PressureCritical ? RedFill : WhiteFill;
        PressureText.Text = Loc.GetString("rbmk-console-pressure-value", ("value", $"{state.Pressure:F0}"));

        CoolantInBar.Value = Math.Clamp(state.CoolantIn, -273f, 1227f);
        CoolantInBar.ForegroundStyleBoxOverride = BlueFill;
        CoolantInText.Text = Loc.GetString("rbmk-console-temperature-value", ("value", $"{state.CoolantIn:F0}"));

        CoolantOutBar.Value = Math.Clamp(state.CoolantOut, -273f, 1227f);
        CoolantOutBar.ForegroundStyleBoxOverride = RedFill;
        CoolantOutText.Text = Loc.GetString("rbmk-console-temperature-value", ("value", $"{state.CoolantOut:F0}"));

        TemperatureLabel.Text = Loc.GetString("rbmk-console-temperature-value", ("value", $"{state.Temperature:F0}"));
        TemperatureLabel.FontColorOverride = state.Temperature >= state.TemperatureMeltdown ? Red
            : state.Temperature >= state.TemperatureCritical ? Amber
            : state.Temperature >= state.TemperatureOperating ? Yellow
            : null;

        IntegrityLabel.Text = $"{state.VesselIntegrity:F0} / {state.MaxVesselIntegrity:F0}";
        IntegrityLabel.FontColorOverride = state.VesselIntegrity <= 0f ? Red
            : state.VesselIntegrity <= state.MaxVesselIntegrity * 0.25f ? Amber
            : null;

        UpdateIntegrityDiagnosis(state);

        RadiationLabel.Text = Loc.GetString("rbmk-console-radiation-value", ("value", $"{state.Radiation:F1}"));
        FuelRodsLabel.Text = $"{state.FuelRods} / {state.MaxFuelRods}";

        // Four traces, one per legend entry, with the ranges RbmkStats.js declares.
        StatsChart.SetSeries(new[]
        {
            new ReactorChart.ChartSeries { Values = state.PowerHistory.ToArray(), Min = 0f, Max = 1500f, Colour = Yellow },
            new ReactorChart.ChartSeries { Values = state.PsiHistory.ToArray(), Min = 0f, Max = 1500f, Colour = White },
            new ReactorChart.ChartSeries { Values = state.CoolantInHistory.ToArray(), Min = -273.15f, Max = 1227f, Colour = Color.FromHex("#7FB3FF") },
            new ReactorChart.ChartSeries { Values = state.CoolantOutHistory.ToArray(), Min = -273.15f, Max = 1227f, Colour = Red },
        });
    }

    /// <summary>
    ///     Explain what the vessel integrity bar is actually losing points to.
    /// </summary>
    /// <remarks>
    ///     A core started from cold drops integrity because the coolant feed has not caught up with
    ///     it yet - which looks identical to a crack in the vessel if all the console shows is a
    ///     falling number. Naming the cause (and the rate) turns it into a plumbing task.
    /// </remarks>
    private void UpdateIntegrityDiagnosis(RbmkConsoleBoundUserInterfaceState state)
    {
        if (!state.Running)
        {
            IntegrityDiagnosisLabel.Text = string.Empty;
            return;
        }

        var damage = state.IntegrityDamage;

        switch (state.IntegrityCause)
        {
            case RbmkIntegrityCause.CoolantStarvation:
                IntegrityDiagnosisLabel.Text = Loc.GetString("rbmk-console-integrity-coolant",
                    ("rate", $"{damage:F1}"),
                    ("percent", $"{state.CoolantSatisfaction * 100f:F0}"));
                IntegrityDiagnosisLabel.FontColorOverride = Amber;
                break;

            case RbmkIntegrityCause.OverTemperature:
                IntegrityDiagnosisLabel.Text = Loc.GetString("rbmk-console-integrity-temperature",
                    ("rate", $"{damage:F1}"));
                IntegrityDiagnosisLabel.FontColorOverride = Red;
                break;

            case RbmkIntegrityCause.OverPressure:
                IntegrityDiagnosisLabel.Text = Loc.GetString("rbmk-console-integrity-pressure",
                    ("rate", $"{damage:F1}"));
                IntegrityDiagnosisLabel.FontColorOverride = Red;
                break;

            default:
                IntegrityDiagnosisLabel.Text = Loc.GetString("rbmk-console-integrity-holding");
                IntegrityDiagnosisLabel.FontColorOverride = null;
                break;
        }
    }

    private void UpdateFuelTab(RbmkConsoleBoundUserInterfaceState state)
    {
        RodList.RemoveAllChildren();

        if (state.Rods.Count == 0)
        {
            RodList.AddChild(new Label { Text = Loc.GetString("rbmk-console-no-fuel") });
            return;
        }

        foreach (var rod in state.Rods)
        {
            var remaining = rod.OriginalFuelPower <= 0f
                ? 0f
                : Math.Clamp(rod.FuelPower / rod.OriginalFuelPower, 0f, 1f);

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };

            var label = new Label
            {
                Text = Loc.GetString("rbmk-console-rod-entry",
                    ("name", rod.Name),
                    ("percent", $"{remaining * 100f:F0}")),
                HorizontalExpand = true,
            };

            var bar = new ProgressBar
            {
                MinValue = 0f,
                MaxValue = 1f,
                Value = remaining,
                SetWidth = 180f,
                SetHeight = 20f,
            };

            bar.ForegroundStyleBoxOverride = remaining >= 0.5f ? GreenFill
                : remaining >= 0.2f ? AmberFill : RedFill;

            var index = rod.Index;
            var eject = new Button
            {
                Text = Loc.GetString("rbmk-console-eject"),
                Disabled = state.Slagged || state.Power > 20f,
            };

            eject.OnPressed += _ => OnEjectRod?.Invoke(index);

            row.AddChild(label);
            row.AddChild(bar);
            row.AddChild(eject);
            RodList.AddChild(row);
        }
    }
}
