        /// <summary>
        /// Palmtree: resolves the sound the preview button should play for the current profile.
        /// </summary>
        private SoundSpecifier? GetVoiceBarkPreviewSound()
        {
            if (Profile is not { } profile)
                return null;

            var voice = profile.VoiceBark;

            // "Default" previews the speech sounds baked into the species mob prototype.
            if (voice == null)
            {
                if (!_prototypeManager.TryIndex(profile.Species, out SpeciesPrototype? species)
                    || !_prototypeManager.TryIndex(species.Prototype, out EntityPrototype? speciesProto)
                    || !speciesProto.TryGetComponent<SpeechComponent>(out var speech, _entManager.ComponentFactory))
                {
                    return null;
                }

                voice = speech.SpeechSounds;
            }

            if (voice == null || !_prototypeManager.TryIndex(voice.Value, out SpeechSoundsPrototype? voiceProto))
                return null;

            var sound = voiceProto.SaySound;
            sound.Params = AudioParams.Default.WithVolume(-2f).WithPitchScale((float) _random.NextGaussian(1, voiceProto.Variation));
            return sound;
        }

