using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._Goobstation.Supermatter.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using System.Diagnostics.CodeAnalysis;
using System.Linq;

namespace Content.Client._Goobstation.Supermatter.Consoles;

[GenerateTypedNameReferences]
public sealed partial class SupermatterConsoleWindow : FancyWindow
{
    private readonly IEntityManager _entManager;

    private EntityUid? _owner;
    private NetEntity? _trackedEntity;

    private SupermatterConsoleEntry[]? _supermatters = null;

    // Palmtree: true when this window belongs to a crystal inspecting itself. Such a window lists
    // exactly one entry, that crystal, and it can never be unfocused.
    private bool _selfInspection;

    public event Action<NetEntity?>? SendFocusChangeMessageAction;

    private bool _autoScrollActive = false;
    private bool _autoScrollAwaitsUpdate = false;

    public SupermatterConsoleWindow(SupermatterConsoleBoundUserInterface userInterface, EntityUid? owner)
    {
        RobustXamlLoader.Load(this);
        _entManager = IoCManager.Resolve<IEntityManager>();

        // Remember the entity this window belongs to; a crystal acts as its own console.
        _owner = owner;

        // Set supermatter monitoring message action
        SendFocusChangeMessageAction += userInterface.SendFocusChangeMessage;
    }

    public void UpdateUI(SupermatterConsoleEntry[] supermatters, SupermatterFocusData? focusData, bool selfInspection)
    {
        if (_owner == null
            || !_entManager.HasComponent<SupermatterConsoleComponent>(_owner.Value))
            return;

        _selfInspection = selfInspection;

        if (_selfInspection)
        {
            // Palmtree: a crystal's own window always shows that crystal. Pin the selection to it
            // and never ask the server to focus anything - there is nothing else to focus.
            _trackedEntity = supermatters.Length > 0 ? supermatters[0].NetEntity : null;
        }
        else
        {
            // Palmtree: the focused crystal can disappear (delaminated, destroyed, towed away).
            // Drop the stale local selection so the window does not keep sending that dead
            // NetEntity back to the server every update.
            if (_trackedEntity is { } tracked
                && !supermatters.Any(entry => entry.NetEntity == tracked))
            {
                _trackedEntity = null;
            }

            if (_trackedEntity != focusData?.NetEntity)
            {
                SendFocusChangeMessageAction?.Invoke(_trackedEntity);
                focusData = null;
            }
        }

        // Retain supermatter data for use inbetween updates
        _supermatters = supermatters;

        // Clear excess entry containers from the table. The "no supermatter" label is not an
        // entry and is handled below, otherwise it would be torn down and rebuilt every update.
        var supermattersCount = _supermatters.Length;

        while (SupermattersTable.ChildCount > supermattersCount)
        {
            var lastChild = SupermattersTable.GetChild(SupermattersTable.ChildCount - 1);
            if (lastChild is not SupermatterEntryContainer)
                break;

            SupermattersTable.RemoveChild(lastChild);
        }

        // Update all entries in each table
        for (var index = 0; index < _supermatters.Length; index++)
            UpdateUIEntry(_supermatters[index], index, SupermattersTable, focusData);

        // If no alerts are active, display a message
        if (supermattersCount == 0 && SupermattersTable.ChildCount == 0)
        {
            var label = new RichTextLabel()
            {
                HorizontalExpand = true,
                VerticalExpand = true,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
            };

            label.SetMarkup(Loc.GetString("supermatter-console-window-no-supermatters"));

            SupermattersTable.AddChild(label);
        }

        // Auto-scroll re-enable
        if (_autoScrollAwaitsUpdate)
        {
            _autoScrollActive = true;
            _autoScrollAwaitsUpdate = false;
        }
    }

    private void UpdateUIEntry(SupermatterConsoleEntry entry, int index, Control table, SupermatterFocusData? focusData = null)
    {
        // Make new UI entry if required
        if (index >= table.ChildCount)
        {
            var newEntryContainer = new SupermatterEntryContainer(entry.NetEntity);

            // On click
            newEntryContainer.FocusButton.OnButtonUp += args =>
            {
                // Palmtree: a crystal's own window has nothing else to focus - do not let the
                // click collapse its stats.
                if (_selfInspection)
                    return;

                if (_trackedEntity == newEntryContainer.NetEntity)
                    _trackedEntity = null;
                else
                    _trackedEntity = newEntryContainer.NetEntity;

                // Send message to console that the focus has changed
                SendFocusChangeMessageAction?.Invoke(_trackedEntity);

                if (_trackedEntity != null)
                    ActivateAutoScrollToFocus();
            };

            // Add the entry to the current table
            table.AddChild(newEntryContainer);
        }

        // Update values and UI elements
        var tableChild = table.GetChild(index);

        if (tableChild is not SupermatterEntryContainer)
        {
            table.RemoveChild(tableChild);
            UpdateUIEntry(entry, index, table, focusData);

            return;
        }

        var entryContainer = (SupermatterEntryContainer)tableChild;

        entryContainer.UpdateEntry(entry, entry.NetEntity == _trackedEntity, focusData);
    }

    protected override void FrameUpdate(FrameEventArgs args) =>
        AutoScrollToFocus();

    private void ActivateAutoScrollToFocus()
    {
        _autoScrollActive = false;
        _autoScrollAwaitsUpdate = true;
    }

    private void AutoScrollToFocus()
    {
        if (!_autoScrollActive)
            return;

        var scroll = SupermattersTable.Parent as ScrollContainer;
        if (scroll == null
            || !TryGetVerticalScrollbar(scroll, out var vScrollbar)
            || !TryGetNextScrollPosition(out float? nextScrollPosition))
        {
            // Nothing to scroll to (the focused entry disappeared); stop doing per-frame work.
            _autoScrollActive = false;
            return;
        }

        vScrollbar.ValueTarget = nextScrollPosition.Value;

        if (MathHelper.CloseToPercent(vScrollbar.Value, vScrollbar.ValueTarget))
            _autoScrollActive = false;
    }

    private bool TryGetVerticalScrollbar(ScrollContainer scroll, [NotNullWhen(true)] out VScrollBar? vScrollBar)
    {
        vScrollBar = null;

        foreach (var child in scroll.Children)
        {
            if (child is not VScrollBar)
                continue;

            var castChild = child as VScrollBar;

            if (castChild != null)
            {
                vScrollBar = castChild;
                return true;
            }
        }

        return false;
    }

    private bool TryGetNextScrollPosition([NotNullWhen(true)] out float? nextScrollPosition)
    {
        nextScrollPosition = null;

        var scroll = SupermattersTable.Parent as ScrollContainer;
        if (scroll == null)
            return false;

        var container = scroll.Children.ElementAt(0) as BoxContainer;
        if (container == null 
            || container.Children.Count() == 0)
            return false;

        // Exit if the heights of the children haven't been initialized yet
        if (!container.Children.Any(x => x.Height > 0))
            return false;

        nextScrollPosition = 0;

        foreach (var control in container.Children)
        {
            if (control == null 
                || control is not SupermatterEntryContainer)
                continue;

            if (((SupermatterEntryContainer)control).NetEntity == _trackedEntity)
                return true;

            nextScrollPosition += control.Height;
        }

        // Failed to find control
        nextScrollPosition = null;

        return false;
    }
}
