using Content.Shared._PS.Modsuits;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.Modsuits;

[GenerateTypedNameReferences]
public sealed partial class ModsuitWindow : DefaultWindow
{
    public event Action? TogglePressed;
    public event Action? SealPressed;

    public ModsuitWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ToggleButton.OnPressed += _ => TogglePressed?.Invoke();
        SealButton.OnPressed += _ => SealPressed?.Invoke();
    }

    public void UpdateState(ModsuitUiState state)
    {
        ThemeLabel.Text = Loc.GetString("modsuit-window-theme", ("theme", state.Theme), ("skin", state.Skin));
        StatusLabel.Text = state.Active
            ? Loc.GetString("modsuit-window-status-active")
            : Loc.GetString("modsuit-window-status-inactive");

        ChargeLabel.Text = state.Infinite
            ? Loc.GetString("modsuit-window-charge-infinite")
            : Loc.GetString("modsuit-window-charge", ("charge", (int) state.Charge), ("max", (int) state.MaxCharge));

        ComplexityLabel.Text = Loc.GetString("modsuit-window-complexity", ("used", state.Complexity), ("max", state.ComplexityMax));

        ToggleButton.Text = state.Active
            ? Loc.GetString("modsuit-window-retract")
            : Loc.GetString("modsuit-window-deploy");
        SealButton.Text = state.Sealed
            ? Loc.GetString("modsuit-window-unseal")
            : Loc.GetString("modsuit-window-seal");
        SealButton.Disabled = !state.Active;

        PartsContainer.DisposeAllChildren();
        foreach (var part in state.Parts)
        {
            var status = part.Equipped
                ? Loc.GetString("modsuit-window-part-equipped")
                : Loc.GetString("modsuit-window-part-stowed");
            PartsContainer.AddChild(new Label
            {
                Text = Loc.GetString("modsuit-window-part", ("slot", part.Slot), ("status", status)),
            });
        }

        ModulesContainer.DisposeAllChildren();
        if (state.Modules.Count == 0)
        {
            ModulesContainer.AddChild(new Label
            {
                Text = Loc.GetString("modsuit-window-no-modules"),
            });
        }

        foreach (var module in state.Modules)
        {
            ModulesContainer.AddChild(new Label
            {
                Text = Loc.GetString(
                    "modsuit-window-module",
                    ("name", module.Name),
                    ("complexity", module.Complexity),
                    ("status", module.Active
                        ? Loc.GetString("modsuit-window-module-active")
                        : Loc.GetString("modsuit-window-module-passive"))),
            });
        }
    }
}
