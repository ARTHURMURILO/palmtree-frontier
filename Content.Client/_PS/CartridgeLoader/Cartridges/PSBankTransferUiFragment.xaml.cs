using System;
using Content.Shared._NF.Bank;
using Content.Shared._PS.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._PS.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class PSBankTransferUiFragment : BoxContainer
{
    public event Action<int, int>? OnTransfer;

    public PSBankTransferUiFragment()
    {
        RobustXamlLoader.Load(this);

        TargetInput.OnTextChanged += _ => ValidateInputs();
        AmountInput.OnTextChanged += _ => ValidateInputs();
        TargetInput.OnTextEntered += _ => Send();
        AmountInput.OnTextEntered += _ => Send();
        SendButton.OnPressed += _ => Send();
    }

    public void UpdateState(PSBankTransferUiState state)
    {
        AccountLabel.Text = $"#{state.AccountNumber:D9}";
        BalanceLabel.Text = Loc.GetString("spesoflow-pay-balance", ("balance", BankSystemExtensions.ToSpesoString(state.Balance)));
        ResultLabel.Text = state.Result;
        ResultLabel.Modulate = state.Success ? Color.FromHex("#33ff33") : Color.FromHex("#cc3333");
        ResultLabel.Visible = !string.IsNullOrEmpty(state.Result);
    }

    private void ValidateInputs()
    {
        var targetText = TargetInput.Text.Trim().TrimStart('#');
        var amountText = AmountInput.Text.Trim();
        var valid = targetText.Length == 9 &&
                    int.TryParse(targetText, out var target) &&
                    target > 0 &&
                    int.TryParse(amountText, out var amount) &&
                    amount > 0;

        SendButton.Disabled = !valid;
    }

    private void Send()
    {
        if (SendButton.Disabled)
            return;

        var targetText = TargetInput.Text.Trim().TrimStart('#');
        var amountText = AmountInput.Text.Trim();
        if (!int.TryParse(targetText, out var target) || !int.TryParse(amountText, out var amount))
            return;

        OnTransfer?.Invoke(target, amount);
    }
}
