using Content.Shared._PS.BluespaceDock;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.BluespaceDock;

/// <summary>
/// One stored ship row in the Bluespace Dock list: name, model and the undock/sell buttons.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class BluespaceDockShipRow : PanelContainer
{
    public event Action<string>? OnUndock;
    public event Action<string>? OnSell;

    private readonly string _shipId;

    public BluespaceDockShipRow(BluespaceDockEntryUi entry)
    {
        RobustXamlLoader.Load(this);

        _shipId = entry.ShipId;
        ShipName.Text = entry.Name;
        ShipModel.Text = entry.Model;

        UndockButton.Disabled = !entry.CanRetrieve;
        UndockButton.ToolTip = entry.BlockedReason != null ? Loc.GetString(entry.BlockedReason) : null;
        UndockButton.OnPressed += _ => OnUndock?.Invoke(_shipId);

        SellButton.Disabled = !entry.CanSell;
        SellButton.OnPressed += _ => OnSell?.Invoke(_shipId);
    }
}
