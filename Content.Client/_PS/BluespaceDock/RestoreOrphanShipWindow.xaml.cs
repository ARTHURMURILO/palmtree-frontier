using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._PS.BluespaceDock;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._PS.BluespaceDock;

/// <summary>
/// Admin window for orphaned ship files: pick one, preview it, restore it into a character's dock or
/// delete it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class RestoreOrphanShipWindow : FancyWindow
{
    public event Action<string>? OnPreview;
    public event Action<string>? OnDelete;
    public event Action? OnDeleteAll;
    public event Action<string, string, string, string>? OnRestore;

    private RestoreOrphanShipEuiState? _state;
    private string? _selected;
    private string _selectedUserId = string.Empty;
    private readonly List<(string File, BoxContainer Row)> _rows = new();

    public RestoreOrphanShipWindow()
    {
        RobustXamlLoader.Load(this);

        PlayerSelect.OnItemSelected += args =>
        {
            if (_state == null || args.Id < 0 || args.Id >= _state.Players.Count)
                return;

            var player = _state.Players[args.Id];
            _selectedUserId = player.UserId;
            UpdateOwnerHint(player.CharacterName);
            UpdateSelection();
        };

        DeleteAllButton.OnPressed += _ => OnDeleteAll?.Invoke();

        RestoreButton.OnPressed += _ =>
        {
            if (_selected is { } file && _selectedUserId.Length > 0)
                OnRestore?.Invoke(file, _selectedUserId, ShipNameField.Text, SuffixField.Text);
        };
    }

    public void UpdateState(RestoreOrphanShipEuiState state)
    {
        _state = state;

        // The list changed: drop a selection that is gone.
        if (_selected != null && state.Ships.All(s => s.Name != _selected))
            _selected = null;

        PlayerSelect.Clear();
        var selected = -1;
        for (var i = 0; i < state.Players.Count; i++)
        {
            var player = state.Players[i];
            var name = string.IsNullOrWhiteSpace(player.CharacterName)
                ? Loc.GetString("restore-orphan-player-no-character")
                : player.CharacterName;
            PlayerSelect.AddItem(name);

            if (player.UserId == _selectedUserId)
                selected = i;
        }

        // The selection can go away (a player disconnecting), and starts empty.
        if (selected < 0)
        {
            _selectedUserId = string.Empty;
            UpdateOwnerHint(null);
        }
        else
        {
            PlayerSelect.Select(selected);
            UpdateOwnerHint(state.Players[selected].CharacterName);
        }

        StatusLabel.Text = state.Status ?? string.Empty;
        StatusLabel.Modulate = state.StatusIsError ? Color.FromHex("#e06c6c") : Color.White;

        RebuildShips();
    }

    private void RebuildShips()
    {
        ShipsList.RemoveAllChildren();
        _rows.Clear();

        if (_state == null)
            return;

        if (_state.Ships.Count == 0)
        {
            ShipsList.AddChild(new Label
            {
                Text = Loc.GetString("restore-orphan-no-ships"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 8),
            });

            UpdateSelection();
            return;
        }

        foreach (var ship in _state.Ships)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
            };

            var select = new Button
            {
                Text = ship.Name,
                HorizontalExpand = true,
                MinWidth = 200,
                ClipText = true,
            };
            select.OnPressed += _ => Select(ship.Name);
            row.AddChild(select);

            row.AddChild(new Label { Text = ship.Modified, MinWidth = 110 });

            var preview = new Button
            {
                Text = Loc.GetString("restore-orphan-preview"),
                MinWidth = 90,
            };
            preview.OnPressed += _ => OnPreview?.Invoke(ship.Name);
            row.AddChild(preview);

            var delete = new ConfirmButton
            {
                Text = Loc.GetString("restore-orphan-delete"),
                ConfirmationText = Loc.GetString("restore-orphan-confirm"),
                MinWidth = 100,
            };
            delete.OnPressed += _ => OnDelete?.Invoke(ship.Name);
            row.AddChild(delete);

            ShipsList.AddChild(row);
            _rows.Add((ship.Name, row));
        }

        UpdateSelection();
    }

    /// <summary>
    /// Shows which character the entry will be written for, so the admin can see it before
    /// restoring.
    /// </summary>
    private void UpdateOwnerHint(string? characterName)
    {
        OwnerHintLabel.Text = string.IsNullOrWhiteSpace(characterName)
            ? Loc.GetString("restore-orphan-target-hint")
            : Loc.GetString("restore-orphan-owner-will-be", ("name", characterName));
    }

    private void Select(string file)
    {
        _selected = file;
        UpdateSelection();
    }

    private void UpdateSelection()
    {
        foreach (var (file, row) in _rows)
            row.Modulate = file == _selected ? Color.FromHex("#5b9bd5") : Color.White;

        RestoreButton.Disabled = _selected == null || _selectedUserId.Length == 0;
    }
}
