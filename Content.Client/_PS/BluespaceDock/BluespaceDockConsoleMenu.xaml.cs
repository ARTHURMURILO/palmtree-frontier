using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NF.Bank;
using Content.Shared._PS.BluespaceDock;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.BluespaceDock;

/// <summary>
/// Bluespace Dock window: the player's stored ships (name/model/undock/sell) plus the store-current-ship
/// and shipyard-style sell buttons. Shows INSERT ID until an ID card is in the console.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class BluespaceDockConsoleMenu : FancyWindow
{
    public event Action? OnDockCurrent;
    public event Action? OnSellActive;
    public event Action<string>? OnUndock;
    public event Action<string>? OnSellStored;

    private BluespaceDockUiState? _state;
    private string _search = string.Empty;

    public BluespaceDockConsoleMenu()
    {
        RobustXamlLoader.Load(this);

        SearchBar.OnTextChanged += args =>
        {
            _search = args.Text;
            RebuildShips();
        };

        DockButton.OnPressed += _ => OnDockCurrent?.Invoke();
        SellActiveButton.OnPressed += _ => OnSellActive?.Invoke();
    }

    public void UpdateState(BluespaceDockUiState state)
    {
        _state = state;

        Contents.Visible = state.HasIdCard;
        WelcomeLabel.Visible = !state.HasIdCard;

        if (!state.HasIdCard)
        {
            WelcomeLabel.Text = Loc.GetString("bluespace-dock-insert-id");
            return;
        }

        WelcomeLabel.Text = Loc.GetString("bluespace-dock-welcome", ("name", state.IdName ?? "???"));
        BalanceLabel.Text = Loc.GetString("bluespace-dock-balance", ("balance", BankSystemExtensions.ToIndependentString(state.Balance)));

        DockButton.Text = Loc.GetString("bluespace-dock-dock-current-cost", ("cost", BankSystemExtensions.ToIndependentString(state.StoreCost)));
        DockButton.Disabled = !state.CanStore;
        DockButton.ToolTip = state.StoreBlockedReason != null ? Loc.GetString(state.StoreBlockedReason) : null;

        SellActiveButton.Disabled = !state.CanSellActive;
        TargetIdButton.Text = state.ActiveShipName != null
            ? Loc.GetString("bluespace-dock-active-ship", ("ship", state.ActiveShipName))
            : Loc.GetString("bluespace-dock-no-active-ship");

        RebuildShips();
    }

    private void RebuildShips()
    {
        ShipsList.RemoveAllChildren();

        if (_state == null)
            return;

        var search = _search.Trim();
        var count = 0;

        foreach (var entry in _state.StoredShips)
        {
            if (search.Length > 0
                && !entry.Name.Contains(search, StringComparison.OrdinalIgnoreCase)
                && !entry.Model.Contains(search, StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var row = new BluespaceDockShipRow(entry);
            row.OnUndock += id => OnUndock?.Invoke(id);
            row.OnSell += id => OnSellStored?.Invoke(id);
            ShipsList.AddChild(row);
            count++;
        }

        if (count == 0)
        {
            ShipsList.AddChild(new Label
            {
                Text = Loc.GetString(search.Length > 0 ? "bluespace-dock-no-matching" : "bluespace-dock-no-ships"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 8),
            });
        }
    }
}
