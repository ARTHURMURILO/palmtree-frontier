using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._PS.BluespaceDock;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._PS.BluespaceDock;

/// <summary>
/// Admin window for player ships: pick one from the dropdown, preview it or delete it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ManageShipsWindow : FancyWindow
{
    public event Action<NetEntity>? OnPreview;
    public event Action<NetEntity>? OnDelete;

    private ManageShipsEuiState? _state;
    private NetEntity? _selected;

    public ManageShipsWindow()
    {
        RobustXamlLoader.Load(this);

        ShipSelect.OnItemSelected += args =>
        {
            if (_state == null || args.Id < 0 || args.Id >= _state.Ships.Count)
                return;

            Select(_state.Ships[args.Id]);
        };

        PreviewButton.OnPressed += _ =>
        {
            if (_selected is { } grid)
                OnPreview?.Invoke(grid);
        };

        DeleteButton.OnPressed += _ =>
        {
            if (_selected is { } grid)
                OnDelete?.Invoke(grid);
        };
    }

    public void UpdateState(ManageShipsEuiState state)
    {
        _state = state;

        // The selection can go away (the ship was deleted) or never have been made.
        if (_selected is { } selected && state.Ships.All(s => s.Grid != selected))
            SelectNone();

        ShipSelect.Clear();
        var index = -1;
        for (var i = 0; i < state.Ships.Count; i++)
        {
            var ship = state.Ships[i];
            var docked = ship.Docked
                ? Loc.GetString("manage-ships-docked")
                : Loc.GetString("manage-ships-undocked");
            ShipSelect.AddItem($"{ship.Name} ({ship.Owner}, {docked})");

            if (_selected is { } current && current == ship.Grid)
                index = i;
        }

        if (_state.Ships.Count == 0)
        {
            ShipHintLabel.Text = Loc.GetString("manage-ships-none");
            SelectNone();
        }
        else if (index >= 0)
        {
            ShipSelect.Select(index);
        }
        else if (_selected == null)
        {
            ShipHintLabel.Text = Loc.GetString("manage-ships-hint");
        }

        StatusLabel.Text = state.Status ?? string.Empty;
        StatusLabel.Modulate = state.StatusIsError ? Color.FromHex("#e06c6c") : Color.White;
    }

    private void Select(ManageShipEntry ship)
    {
        _selected = ship.Grid;
        ShipHintLabel.Text = Loc.GetString("manage-ships-selected", ("name", ship.Name), ("owner", ship.Owner));
        PreviewButton.Disabled = false;
        DeleteButton.Disabled = false;
    }

    private void SelectNone()
    {
        _selected = null;
        PreviewButton.Disabled = true;
        DeleteButton.Disabled = true;
    }
}
