using Content.Shared._PS.Protean;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.Protean;

[GenerateTypedNameReferences]
public sealed partial class ProteanWindow : DefaultWindow
{
    public event Action? FoldPressed;
    public event Action? LockPressed;
    public event Action? EjectPressed;
    public event Action? ServoPressed;
    public event Action? LowPowerPressed;
    public event Action? HealPressed;

    public ProteanWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        FoldButton.OnPressed += _ => FoldPressed?.Invoke();
        LockButton.OnPressed += _ => LockPressed?.Invoke();
        EjectButton.OnPressed += _ => EjectPressed?.Invoke();
        ServoButton.OnPressed += _ => ServoPressed?.Invoke();
        LowPowerButton.OnPressed += _ => LowPowerPressed?.Invoke();
        HealButton.OnPressed += _ => HealPressed?.Invoke();
    }

    public void UpdateState(ProteanUiState state)
    {
        MetalLabel.Text = Loc.GetString("protean-window-metal", ("metal", (int) state.Metal), ("max", (int) state.MaxMetal));
        StatusLabel.Text = state.Folded
            ? Loc.GetString("protean-window-folded")
            : Loc.GetString("protean-window-unfolded");
        LockLabel.Text = state.Locked
            ? Loc.GetString("protean-window-locked")
            : Loc.GetString("protean-window-unlocked");
        LockButton.Text = state.Locked
            ? Loc.GetString("protean-window-unlock")
            : Loc.GetString("protean-window-lock");
        FoldButton.Text = state.Folded
            ? Loc.GetString("protean-window-unfold")
            : Loc.GetString("protean-window-fold");
        FoldButton.Disabled = state.Folded ? !state.CanUnfold : !state.CanFold;
        LockButton.Disabled = !state.HasSuit;
        EjectButton.Text = Loc.GetString("protean-window-eject");
        EjectButton.Disabled = !state.HasStoredSuit;
        ServoButton.Text = Loc.GetString("protean-window-servo");
        ServoButton.Disabled = !state.ServoReady;

        LowPowerButton.Text = state.LowPower
            ? Loc.GetString("protean-window-low-power-off")
            : Loc.GetString("protean-window-low-power-on");
        LowPowerButton.Disabled = state.Folded;
        HealButton.Text = Loc.GetString("protean-window-heal");
        HealButton.Disabled = !state.CanHeal;
    }
}
