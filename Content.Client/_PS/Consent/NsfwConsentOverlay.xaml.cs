using Content.Client.Lobby;
using Content.Client.Message;
using Content.Shared._PS.Consent;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Localization;

namespace Content.Client._PS.Consent;

/// <summary>
/// Palmtree: the one-time NSFW consent prompt (age gate). Shown as a full-screen overlay on the
/// lobby; while visible it swallows all input, so the player cannot customize their character,
/// ready up or otherwise interact with the lobby until they answer. The answer is stored on the
/// account and can afterwards only be changed with the <c>nsfwtoggle</c> console command.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NsfwConsentOverlay : PanelContainer
{
    [Dependency] private readonly IClientPreferencesManager _preferencesManager = default!;

    public NsfwConsentOverlay()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TitleLabel.Text = Loc.GetString("nsfw-consent-title");
        BodyLabel.SetMarkup(Loc.GetString("nsfw-consent-body"));

        AcceptButton.Text = Loc.GetString("nsfw-consent-accept");
        DeclineButton.Text = Loc.GetString("nsfw-consent-decline");

        AcceptButton.OnPressed += _ => Answer(true);
        DeclineButton.OnPressed += _ => Answer(false);

        UpdateVisibility();
    }

    private void Answer(bool allowed)
    {
        _preferencesManager.UpdateNsfwConsent(allowed);
        UpdateVisibility();
    }

    /// <summary>
    /// Shows the prompt only while the account has not answered the one-time question. Hidden
    /// while preferences are still loading (the server also refuses to ready unanswered players).
    /// </summary>
    public void UpdateVisibility()
    {
        Visible = _preferencesManager.Preferences?.NsfwConsent == NsfwConsentState.Unanswered;
    }
}
