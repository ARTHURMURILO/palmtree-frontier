using Content.Shared._PS.ShipRegistry;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.ShipRegistry;

/// <summary>
/// Window for the ship preview: just a camera viewport, no controls beyond the mouse wheel zoom.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ShipPreviewWindow : DefaultWindow
{
    public ShipPreviewWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ContentsContainer.Margin = new Thickness(5, 0, 5, 0);
    }

    public void SetState(ShipPreviewEuiState state)
    {
        Title = Loc.GetString("ship-registrar-preview-title-ship", ("ship", state.ShipName));
    }
}
