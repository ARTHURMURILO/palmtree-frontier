using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NF.Bank;
using Content.Shared._PS.ShipRegistry;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._PS.ShipRegistry;

/// <summary>
/// Ship Registrar window: pick a docked, unregistered grid from the list (with a live preview),
/// name it and register it as a civilian vessel.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ShipRegistrarConsoleMenu : FancyWindow
{
    public event Action? OnPrivilegedId;
    public event Action? OnTargetId;
    public event Action<NetEntity, string, string>? OnRegister;
    public event Action<NetEntity>? OnPreview;

    private ShipRegistrarUiState? _state;
    private NetEntity? _selected;
    private string _search = string.Empty;
    private bool _locked = true;
    private readonly List<(NetEntity Grid, BoxContainer Row)> _rows = new();

    public ShipRegistrarConsoleMenu()
    {
        RobustXamlLoader.Load(this);

        SearchBar.OnTextChanged += args =>
        {
            _search = args.Text;
            RebuildGrids();
        };

        // The server truncates too, but showing it as it happens avoids surprise.
        NameField.OnTextChanged += args =>
        {
            ClampField(NameField, args.Text, ShipRegistrarConsoleComponent.MaxNameLength);
            UpdateFullNamePreview();
        };
        SuffixField.OnTextChanged += args =>
        {
            ClampField(SuffixField, args.Text, ShipRegistrarConsoleComponent.MaxSuffixLength);
            UpdateFullNamePreview();
        };

        PrivilegedIdButton.OnPressed += _ => OnPrivilegedId?.Invoke();
        TargetIdButton.OnPressed += _ => OnTargetId?.Invoke();
        RegisterButton.OnPressed += _ =>
        {
            if (_selected is { } grid)
                OnRegister?.Invoke(grid, NameField.Text, SuffixField.Text);
        };
    }

    public void UpdateState(ShipRegistrarUiState state)
    {
        _state = state;

        // The window stays fully visible without a privileged ID (so the two ID buttons can be used
        // to insert or take back a held ID); everything else is locked until one is in.
        _locked = !state.HasPrivilegedId;
        WelcomeLabel.Text = _locked
            ? Loc.GetString("ship-registrar-insert-id")
            : Loc.GetString("ship-registrar-welcome", ("name", state.PrivilegedIdName ?? "???"));

        SearchBar.Editable = !_locked;
        NameField.Editable = !_locked;
        SuffixField.Editable = !_locked;

        PrivilegedIdButton.Text = Loc.GetString("ship-registrar-privileged-id",
            ("name", state.PrivilegedIdName ?? Loc.GetString("ship-registrar-id-missing")));
        TargetIdButton.Text = Loc.GetString("ship-registrar-target-id",
            ("name", state.TargetIdName ?? Loc.GetString("ship-registrar-id-missing")));

        BalanceLabel.Text = Loc.GetString("ship-registrar-balance", ("balance", BankSystemExtensions.ToIndependentString(state.Balance)));
        FeeLabel.Text = Loc.GetString("ship-registrar-fee", ("fee", BankSystemExtensions.ToIndependentString(state.Fee)));

        UpdateFullNamePreview();

        // A selected grid that is gone (registered, undocked, ...) is no longer selectable.
        if (_selected is { } selected && state.Grids.All(g => g.Grid != selected))
            _selected = null;

        RebuildGrids();
    }

    private void RebuildGrids()
    {
        GridsList.RemoveAllChildren();
        _rows.Clear();

        if (_state == null)
            return;

        var search = _search.Trim();
        var count = 0;

        foreach (var grid in _state.Grids)
        {
            if (search.Length > 0
                && !grid.Name.Contains(search, StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
            };

            row.AddChild(new Label
            {
                Text = grid.Name,
                HorizontalExpand = true,
                MinWidth = 140,
                ClipText = true,
            });
            row.AddChild(new Label { Text = grid.Size, MinWidth = 80 });
            row.AddChild(new Label
            {
                Text = Loc.GetString("ship-registrar-value", ("value", BankSystemExtensions.ToIndependentString(grid.Value))),
                MinWidth = 80,
            });

            var selectButton = new Button
            {
                Text = Loc.GetString("ship-registrar-select"),
                MinWidth = 80,
                Disabled = _locked,
            };
            selectButton.OnPressed += _ => Select(grid.Grid);

            var previewButton = new Button
            {
                Text = Loc.GetString("ship-registrar-preview"),
                MinWidth = 90,
                Disabled = _locked,
            };
            previewButton.OnPressed += _ => OnPreview?.Invoke(grid.Grid);

            row.AddChild(selectButton);
            row.AddChild(previewButton);

            GridsList.AddChild(row);
            _rows.Add((grid.Grid, row));
            count++;
        }

        if (count == 0)
        {
            GridsList.AddChild(new Label
            {
                Text = Loc.GetString(search.Length > 0 ? "ship-registrar-no-matching" : "ship-registrar-no-grids"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 8),
            });
        }

        UpdateSelection();
    }

    /// <summary>
    /// Shows the name the deed will carry (base name + registration, without appending the suffix
    /// twice when the name already ends with it), so the result is never a surprise.
    /// </summary>
    private void UpdateFullNamePreview()
    {
        var full = ShipNameHelper.BuildFullName(NameField.Text, SuffixField.Text);
        FullNamePreviewLabel.Text = Loc.GetString("ship-registrar-full-name-preview",
            ("name", full.Length == 0 ? Loc.GetString("ship-registrar-full-name-none") : full));
    }

    private static void ClampField(LineEdit field, string text, int maxLength)
    {
        if (text.Length > maxLength)
            field.Text = text[..maxLength];
    }

    private void Select(NetEntity grid)
    {
        _selected = grid;
        UpdateSelection();
    }

    private void UpdateSelection()
    {
        foreach (var (grid, row) in _rows)
            row.Modulate = grid == _selected ? Color.FromHex("#5b9bd5") : Color.White;

        var canRegister = _selected != null && _state is { HasTargetId: true };
        RegisterButton.Disabled = _locked || !canRegister;

        if (_state == null)
            return;

        if (_selected is { } selected
            && _state.Grids.FirstOrDefault(g => g.Grid == selected) is { } entry)
        {
            SelectionLabel.Text = Loc.GetString("ship-registrar-selected", ("name", entry.Name));
        }
        else
        {
            SelectionLabel.Text = Loc.GetString("ship-registrar-no-selection");
        }
    }
}
