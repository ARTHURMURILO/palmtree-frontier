using System.Numerics;
using Content.Client.Eye;
using Content.Shared._PS.ShipRegistry;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Timing;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._PS.ShipRegistry;

/// <summary>
/// Camera viewport for the ship preview. This is the admin camera control with the follow/pop-out
/// buttons removed: the eye is attached to the preview camera entity and the mouse wheel zooms.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ShipPreviewControl : Control
{
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IClientGameTiming _timing = default!;

    private readonly EyeLerpingSystem _eyeLerpingSystem;
    private readonly FixedEye _defaultEye = new();
    private ShipPreviewEuiState? _nextState;

    private const float MinimumZoom = 0.1f;
    private const float MaximumZoom = 2.0f;

    public EntityUid? CurrentCamera;
    public float Zoom = 1.0f;

    public ShipPreviewControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _eyeLerpingSystem = _entManager.System<EyeLerpingSystem>();

        CameraView.Eye = _defaultEye;
        CameraView.OnResized += OnResized;
    }

    private new void OnResized()
    {
        var width = Math.Max(CameraView.PixelWidth, (int) Math.Floor(CameraView.MinWidth));
        var height = Math.Max(CameraView.PixelHeight, (int) Math.Floor(CameraView.MinHeight));

        CameraView.ViewportSize = new Vector2i(width, height);
    }

    protected override void MouseWheel(GUIMouseWheelEventArgs args)
    {
        base.MouseWheel(args);

        if (CameraView.Eye == null)
            return;

        Zoom = Math.Clamp(Zoom - args.Delta.Y * 0.15f * Zoom, MinimumZoom, MaximumZoom);
        CameraView.Eye.Zoom = new Vector2(Zoom, Zoom);
        args.Handle();
    }

    public void SetState(ShipPreviewEuiState state)
    {
        _nextState = state;

        // Fit the ship in the window: bigger ships start further out.
        var extent = Math.Max(state.Size.X, state.Size.Y);
        Zoom = Math.Clamp(6f / Math.Max(extent, 1f), MinimumZoom, 1f);
        CameraView.Eye = CameraView.Eye ?? _defaultEye;
        CameraView.Eye.Zoom = new Vector2(Zoom, Zoom);
    }

    // EUIs update before the gamestate is applied, so the camera entity has to be resolved on a
    // later frame (same workaround as the admin camera control).
    protected override void FrameUpdate(FrameEventArgs args)
    {
        var state = _nextState;
        if (state == null || _timing.LastRealTick < state.Tick)
            return;

        if (!_entManager.TryGetEntity(state.Camera, out var cameraUid))
            return;

        if (CurrentCamera == null)
        {
            _eyeLerpingSystem.AddEye(cameraUid.Value);
            CurrentCamera = cameraUid;
        }
        else if (CurrentCamera != cameraUid)
        {
            _eyeLerpingSystem.RemoveEye(CurrentCamera.Value);
            _eyeLerpingSystem.AddEye(cameraUid.Value);
            CurrentCamera = cameraUid;
        }

        if (_entManager.TryGetComponent<EyeComponent>(CurrentCamera, out var eye))
        {
            CameraView.Eye = eye.Eye ?? _defaultEye;

            // The eye object only exists once the camera entity is known, so the zoom (initial fit
            // and mouse wheel) is applied here rather than in SetState.
            CameraView.Eye.Zoom = new Vector2(Zoom, Zoom);
        }
    }
}
