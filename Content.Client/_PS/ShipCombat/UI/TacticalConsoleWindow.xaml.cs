using System;
using System.Collections.Generic;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._PS.ShipCombat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Localization;
using Robust.Shared.Map;
using Robust.Shared.Maths;
using Robust.Shared.Physics.Components;

namespace Content.Client._PS.ShipCombat.UI;

/// <summary>
/// Palmtree: the ship targeting ("tactical") console window. The IFF view is the shared shuttle
/// radar control; the right panel carries the condition and fire controls.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TacticalConsoleWindow : FancyWindow
{
    // Palmtree: tactical consoles are dark red instead of the default gray.
    private static readonly Color WindowBackgroundColor = Color.FromHex("#2A1518");
    private static readonly Color WindowHeadingColor = Color.FromHex("#3A1A1E");

    private static readonly Color ConditionGreenColor = Color.FromHex("#3BD63B");
    private static readonly Color ConditionYellowColor = Color.FromHex("#FFD700");
    private static readonly Color ConditionRedColor = Color.FromHex("#FF3B3B");
    private static readonly Color WarningColor = Color.FromHex("#FF3B3B");

    [Dependency] private readonly IEntityManager _entManager = default!;

    public event Action<ShipCondition>? OnConditionConfirmed;
    public event Action<bool>? OnAutomaticConditionChanged;
    public event Action<bool>? OnAutomaticFireChanged;
    public event Action<bool>? OnAutomaticRetaliationChanged;
    public event Action<ShipWeaponMode>? OnWeaponModeChanged;

    /// <summary>Raised when the player clicks the radar (map coordinates of the click).</summary>
    public event Action<EntityCoordinates>? OnLockRequested;

    /// <summary>Raised when the player presses CLEAR LOCK.</summary>
    public event Action? OnClearLockRequested;

    /// <summary>The condition the player selected but has not confirmed yet.</summary>
    private ShipCondition? _pendingCondition;

    /// <summary>The condition the server last reported.</summary>
    private ShipCondition _condition = ShipCondition.Green;

    private readonly TacticalOverlayState _overlay = new();

    /// <summary>Armed contacts that render red on the radar.</summary>
    private readonly HashSet<EntityUid> _hostileGrids = new();

    public TacticalConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        WindowBackgroundPanel.ModulateSelfOverride = WindowBackgroundColor;
        WindowHeadingPanel.ModulateSelfOverride = WindowHeadingColor;

        // Palmtree: the tactical console sees hidden-IFF contacts and draws its own overlays.
        NavRadar.ShowHiddenIFF = true;
        NavRadar.TacticalOverlay = _overlay;
        NavRadar.OnRadarClick += coords => OnLockRequested?.Invoke(coords);

        ConditionOption.AddItem(Loc.GetString("tactical-console-condition-green"), (int) ShipCondition.Green);
        ConditionOption.AddItem(Loc.GetString("tactical-console-condition-yellow"), (int) ShipCondition.Yellow);
        ConditionOption.AddItem(Loc.GetString("tactical-console-condition-red"), (int) ShipCondition.Red);
        ConditionOption.OnItemSelected += args =>
        {
            ConditionOption.SelectId(args.Id);
            SetPendingCondition((ShipCondition) args.Id);
        };

        WeaponsOption.AddItem(Loc.GetString("tactical-console-weapons-master-safe"), (int) ShipWeaponMode.MasterSafe);
        WeaponsOption.AddItem(Loc.GetString("tactical-console-weapons-all"), (int) ShipWeaponMode.All);
        WeaponsOption.AddItem(Loc.GetString("tactical-console-weapons-primary"), (int) ShipWeaponMode.Primary);
        WeaponsOption.AddItem(Loc.GetString("tactical-console-weapons-secondary"), (int) ShipWeaponMode.Secondary);
        WeaponsOption.AddItem(Loc.GetString("tactical-console-weapons-aux"), (int) ShipWeaponMode.Aux);
        WeaponsOption.OnItemSelected += args =>
        {
            WeaponsOption.SelectId(args.Id);
            OnWeaponModeChanged?.Invoke((ShipWeaponMode) args.Id);
        };

        ConditionConfirmButton.OnPressed += _ =>
        {
            if (_pendingCondition is { } condition)
                OnConditionConfirmed?.Invoke(condition);

            ClearPendingCondition();
        };
        ConditionCancelButton.OnPressed += _ =>
        {
            ClearPendingCondition();
            ConditionOption.SelectId((int) _condition);
        };

        AutoConditionCheck.OnToggled += args => OnAutomaticConditionChanged?.Invoke(args.Pressed);
        AutoFireCheck.OnToggled += args => OnAutomaticFireChanged?.Invoke(args.Pressed);
        AutoRetaliationCheck.OnToggled += args => OnAutomaticRetaliationChanged?.Invoke(args.Pressed);

        ClearLockButton.OnPressed += _ => OnClearLockRequested?.Invoke();
    }

    public void SetConsole(EntityUid console)
    {
        NavRadar.SetConsole(console);
    }

    public void UpdateState(TacticalConsoleBoundUserInterfaceState state)
    {
        NavRadar.UpdateState(state.NavState);

        _condition = state.Condition;
        ConditionDisplayLabel.Text = Loc.GetString(ConditionLocKey(state.Condition));
        ConditionDisplayLabel.FontColorOverride = ConditionColor(state.Condition);

        // While a change is waiting for confirmation the dropdown keeps showing the pending pick.
        if (_pendingCondition == null)
            ConditionOption.SelectId((int) state.Condition);

        WeaponsOption.SelectId((int) state.WeaponMode);

        AutoConditionCheck.Pressed = state.AutomaticCondition;
        AutoFireCheck.Pressed = state.AutomaticFire;
        AutoRetaliationCheck.Pressed = state.AutomaticRetaliation;

        LockStatusLabel.Text = FormatStatus("tactical-console-lock", state.BeingLocked);
        LockStatusLabel.FontColorOverride = state.BeingLocked ? WarningColor : null;
        MslStatusLabel.Text = FormatStatus("tactical-console-msl", state.IncomingMissile);
        MslStatusLabel.FontColorOverride = state.IncomingMissile ? WarningColor : null;
        TargetStatusLabel.Text = state.TargetName is { } targetName
            ? Loc.GetString("tactical-console-target-name", ("name", targetName))
            : Loc.GetString("tactical-console-target-none");

        // Fire controls need a lock, an armed weapon group and a non-GREEN condition.
        var canFire = state.Condition != ShipCondition.Green
                      && state.WeaponMode != ShipWeaponMode.MasterSafe
                      && state.HasLock;
        FireButton.Disabled = !canFire;
        FireTorpedoesButton.Disabled = !canFire;
        ClearLockButton.Disabled = !state.HasLock;

        UpdateTacticalOverlay(state);
    }

    private void UpdateTacticalOverlay(TacticalConsoleBoundUserInterfaceState state)
    {
        _overlay.LockTargetPosition = state.LockTarget is { } netTarget
            ? GetGridMapPosition(netTarget)
            : null;

        _overlay.LockCursors.Clear();
        _hostileGrids.Clear();

        foreach (var contact in state.Contacts)
        {
            // Armed contacts render red.
            if (contact.Armed && _entManager.TryGetEntity(contact.Grid, out var armed) && armed is { } armedUid)
                _hostileGrids.Add(armedUid);

            // Contacts locking this ship get a yellow cursor (flashing when armed).
            if (contact.LockingUs && GetGridMapPosition(contact.Grid) is { } position)
                _overlay.LockCursors.Add(new TacticalLockCursor(position, contact.Armed));
        }

        NavRadar.HostileGrids = _hostileGrids;
        NavRadar.TacticalOverlay = _overlay;
    }

    /// <summary>
    /// The map position of a grid's centre, or null when it is not loaded client-side.
    /// </summary>
    private Vector2? GetGridMapPosition(NetEntity netEntity)
    {
        if (!_entManager.TryGetEntity(netEntity, out var entity) || entity is not { } uid)
            return null;

        var center = _entManager.TryGetComponent<PhysicsComponent>(uid, out var physics)
            ? physics.LocalCenter
            : Vector2.Zero;

        return _entManager.System<SharedTransformSystem>()
            .ToMapCoordinates(new EntityCoordinates(uid, center)).Position;
    }

    private void SetPendingCondition(ShipCondition condition)
    {
        if (_pendingCondition == condition)
            return;

        _pendingCondition = condition;
        ConditionConfirmLabel.Text = Loc.GetString("tactical-console-condition-confirm",
            ("condition", Loc.GetString(ConditionLocKey(condition))));
        ConditionConfirmBox.Visible = true;
    }

    private void ClearPendingCondition()
    {
        _pendingCondition = null;
        ConditionConfirmBox.Visible = false;
    }

    private static string FormatStatus(string labelKey, bool value)
    {
        return $"{Loc.GetString(labelKey)}: {Loc.GetString(value ? "tactical-console-yes" : "tactical-console-no")}";
    }

    private static string ConditionLocKey(ShipCondition condition)
    {
        return condition switch
        {
            ShipCondition.Green => "tactical-console-condition-green",
            ShipCondition.Yellow => "tactical-console-condition-yellow",
            ShipCondition.Red => "tactical-console-condition-red",
            _ => "tactical-console-condition-green",
        };
    }

    private static Color ConditionColor(ShipCondition condition)
    {
        return condition switch
        {
            ShipCondition.Green => ConditionGreenColor,
            ShipCondition.Yellow => ConditionYellowColor,
            ShipCondition.Red => ConditionRedColor,
            _ => ConditionGreenColor,
        };
    }
}
