using System;
using System.Collections.Generic;
using Content.Client.UserInterface.Controls;
using Content.Shared._PS.ShipCombat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Localization;
using Robust.Shared.Maths;

namespace Content.Client._PS.ShipCombat.UI;

/// <summary>
/// Palmtree: the engineering shielding console window: power pools, presets, shield facing
/// redistribution and the system alerts.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ShieldingConsoleWindow : FancyWindow
{
    // Palmtree: shielding consoles are dark yellow instead of the default gray.
    private static readonly Color InactivePoolColor = Color.FromHex("#555555");

    private static readonly Color WindowBackgroundColor = Color.FromHex("#2A2414");
    private static readonly Color WindowHeadingColor = Color.FromHex("#3A3018");

    private static readonly Color ConditionGreenColor = Color.FromHex("#3BD63B");
    private static readonly Color ConditionYellowColor = Color.FromHex("#FFD700");
    private static readonly Color ConditionRedColor = Color.FromHex("#FF3B3B");

    public event Action<ShipCondition>? OnConditionConfirmed;
    public event Action<ShipPowerPool, int>? OnPoolChanged;
    public event Action<ShipPowerPool, bool>? OnPoolLockChanged;
    public event Action<ShipPowerPreset>? OnPresetSelected;
    public event Action<ShieldFacing>? OnRedistribute;

    /// <summary>Raised when the player toggles the console's Silent checkbox.</summary>
    public event Action<bool>? OnSilentChanged;

    private readonly Dictionary<ShipPowerPool, ThresholdSlider> _sliders = new();
    private readonly Dictionary<ShipPowerPool, Label> _valueLabels = new();
    private readonly Dictionary<ShipPowerPool, Label> _alertLabels = new();
    private readonly Dictionary<ShipPowerPool, CheckBox> _lockChecks = new();

    private ShipCondition? _pendingCondition;
    private ShipCondition _condition = ShipCondition.Green;

    /// <summary>The pool currently being dragged: its slider is not overwritten by state updates.</summary>
    private ShipPowerPool? _editingPool;

    public ShieldingConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        WindowBackgroundPanel.ModulateSelfOverride = WindowBackgroundColor;
        WindowHeadingPanel.ModulateSelfOverride = WindowHeadingColor;

        ConditionOption.AddItem(Loc.GetString("tactical-console-condition-green"), (int) ShipCondition.Green);
        ConditionOption.AddItem(Loc.GetString("tactical-console-condition-yellow"), (int) ShipCondition.Yellow);
        ConditionOption.AddItem(Loc.GetString("tactical-console-condition-red"), (int) ShipCondition.Red);
        ConditionOption.OnItemSelected += args =>
        {
            ConditionOption.SelectId(args.Id);
            SetPendingCondition((ShipCondition) args.Id);
        };

        ConditionConfirmButton.OnPressed += _ =>
        {
            if (_pendingCondition is { } condition)
                OnConditionConfirmed?.Invoke(condition);

            ClearPendingCondition();
        };
        ConditionCancelButton.OnPressed += _ =>
        {
            ClearPendingCondition();
            ConditionOption.SelectId((int) _condition);
        };

        // Shield facing redistribution.
        FacingForeButton.OnPressed += _ => OnRedistribute?.Invoke(ShieldFacing.Fore);
        FacingStarboardButton.OnPressed += _ => OnRedistribute?.Invoke(ShieldFacing.Starboard);
        FacingAftButton.OnPressed += _ => OnRedistribute?.Invoke(ShieldFacing.Aft);
        FacingPortButton.OnPressed += _ => OnRedistribute?.Invoke(ShieldFacing.Port);
        FacingAllButton.OnPressed += _ => OnRedistribute?.Invoke(ShieldFacing.All);

        // Power pools: sliders, value labels, alerts and locks.
        RegisterPool(ShipPowerPool.Shields, ShieldSlider, ShieldValueLabel, ShieldAlertLabel, ShieldLockCheck);
        RegisterPool(ShipPowerPool.Weapons, WeaponSlider, WeaponValueLabel, WeaponAlertLabel, WeaponLockCheck);
        RegisterPool(ShipPowerPool.Thrusters, ThrusterSlider, ThrusterValueLabel, ThrusterAlertLabel, ThrusterLockCheck);
        RegisterPool(ShipPowerPool.Auxiliary, AuxiliarySlider, AuxiliaryValueLabel, AuxiliaryAlertLabel, AuxiliaryLockCheck);

        PresetAttackButton.OnPressed += _ => OnPresetSelected?.Invoke(ShipPowerPreset.Attack);
        PresetDefenseButton.OnPressed += _ => OnPresetSelected?.Invoke(ShipPowerPreset.Defense);
        PresetBalancedButton.OnPressed += _ => OnPresetSelected?.Invoke(ShipPowerPreset.Balanced);
        SilentCheck.OnToggled += args => OnSilentChanged?.Invoke(args.Pressed);
    }

    public void SetConsole(EntityUid console)
    {
        NavRadar.SetConsole(console);
    }

    public void UpdateState(ShieldingConsoleBoundUserInterfaceState state)
    {
        NavRadar.UpdateState(state.NavState);

        _condition = state.Condition;
        ConditionDisplayLabel.Text = Loc.GetString(ConditionLocKey(state.Condition));
        ConditionDisplayLabel.FontColorOverride = ConditionColor(state.Condition);

        if (_pendingCondition == null)
            ConditionOption.SelectId((int) state.Condition);

        SetPool(ShipPowerPool.Shields, state.ShieldPower, state.ShieldLocked, state.ShieldsAlert);
        SetPool(ShipPowerPool.Weapons, state.WeaponPower, state.WeaponLocked, state.WeaponsAlert);
        SetPool(ShipPowerPool.Thrusters, state.ThrusterPower, state.ThrusterLocked, state.ThrustersAlert);
        SetPool(ShipPowerPool.Auxiliary, state.AuxiliaryPower, state.AuxiliaryLocked, state.AuxiliaryAlert);

        // Facings: charge / maximum, with a DOWN marker for collapsed ones.
        SetFacing(FacingForeLabel, FacingForeBar, state, ShieldFacing.Fore);
        SetFacing(FacingStarboardLabel, FacingStarboardBar, state, ShieldFacing.Starboard);
        SetFacing(FacingAftLabel, FacingAftBar, state, ShieldFacing.Aft);
        SetFacing(FacingPortLabel, FacingPortBar, state, ShieldFacing.Port);

        RedistributeCooldownLabel.Text = state.RedistributionCooldown > 0f
            ? Loc.GetString("shielding-console-redistribute-cooldown", ("seconds", (int) MathF.Ceiling(state.RedistributionCooldown)))
            : Loc.GetString("shielding-console-redistribute-ready");

        SilentCheck.Pressed = state.Silent;

        // Absent systems are greyed out: their points feed the grid instead.
        for (var i = 0; i < 4; i++)
        {
            var pool = (ShipPowerPool) i;
            var active = state.ActivePools[i];
            _sliders[pool].MouseFilter = active ? MouseFilterMode.Stop : MouseFilterMode.Ignore;
            _lockChecks[pool].Disabled = !active;
            _sliders[pool].ModulateSelfOverride = active ? null : InactivePoolColor;
        }
    }

    private void RegisterPool(
        ShipPowerPool pool,
        ThresholdSlider slider,
        Label valueLabel,
        Label alertLabel,
        CheckBox lockCheck)
    {
        _sliders[pool] = slider;
        _valueLabels[pool] = valueLabel;
        _alertLabels[pool] = alertLabel;
        _lockChecks[pool] = lockCheck;

        slider.MinValue = ShipPowerConstants.PoolMin;
        slider.MaxValue = ShipPowerConstants.PoolMax;
        slider.Threshold = 100f;

        slider.OnGrabbed += _ => _editingPool = pool;
        slider.OnReleased += s =>
        {
            _editingPool = null;
            OnPoolChanged?.Invoke(pool, (int) s.Value);
        };
        slider.OnValueChanged += s => valueLabel.Text = ((int) s.Value).ToString();

        lockCheck.OnToggled += args => OnPoolLockChanged?.Invoke(pool, args.Pressed);
    }

    private void SetPool(ShipPowerPool pool, int value, bool locked, bool alert)
    {
        var slider = _sliders[pool];

        // Do not fight the player while they are dragging a slider.
        if (_editingPool != pool)
            slider.Value = value;

        _valueLabels[pool].Text = value.ToString();
        _alertLabels[pool].Visible = alert;
        _lockChecks[pool].Pressed = locked;
    }

    private static void SetFacing(Label label, ProgressBar bar, ShieldingConsoleBoundUserInterfaceState state, ShieldFacing facing)
    {
        var index = (int) facing;
        var charge = (int) state.Facings[index];
        var max = (int) state.MaxPerFacing;

        // Mini-bar: how much of the facing's capacity is left.
        bar.MaxValue = MathF.Max(1f, state.MaxPerFacing);
        bar.Value = state.Facings[index];

        label.Text = state.FacingsUp[index]
            ? $"{charge} / {max}"
            : Loc.GetString("shielding-console-facing-down", ("charge", charge), ("max", max));
    }

    private void SetPendingCondition(ShipCondition condition)
    {
        if (_pendingCondition == condition)
            return;

        _pendingCondition = condition;
        ConditionConfirmLabel.Text = Loc.GetString("tactical-console-condition-confirm",
            ("condition", Loc.GetString(ConditionLocKey(condition))));
        ConditionConfirmBox.Visible = true;
    }

    private void ClearPendingCondition()
    {
        _pendingCondition = null;
        ConditionConfirmBox.Visible = false;
    }

    private static string ConditionLocKey(ShipCondition condition)
    {
        return condition switch
        {
            ShipCondition.Green => "tactical-console-condition-green",
            ShipCondition.Yellow => "tactical-console-condition-yellow",
            ShipCondition.Red => "tactical-console-condition-red",
            _ => "tactical-console-condition-green",
        };
    }

    private static Color ConditionColor(ShipCondition condition)
    {
        return condition switch
        {
            ShipCondition.Green => ConditionGreenColor,
            ShipCondition.Yellow => ConditionYellowColor,
            ShipCondition.Red => ConditionRedColor,
            _ => ConditionGreenColor,
        };
    }
}
