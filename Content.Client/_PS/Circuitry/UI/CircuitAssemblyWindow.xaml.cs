using System;
using System.Numerics;
using Content.Shared._PS.Circuitry;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.Circuitry.UI;

[GenerateTypedNameReferences]
public sealed partial class CircuitAssemblyWindow : BaseWindow
{
    private const int DragMarginSize = 7;

    public event Action<string>? OnEject;
    public event Action? OnOpenProgram;
    public event Action? OnRun;
    public event Action? OnStop;
    public event Action<string>? OnRename;
    public event Action<bool>? OnLock;
    public event Action<string>? OnTransferOwner;

    private string? _lastServerName;
    private string? _lastServerOwner;
    private bool _nameInitialized;
    private bool _ownerInitialized;
    private CircuitAssemblyState? _lastState;

    public CircuitAssemblyWindow()
    {
        RobustXamlLoader.Load(this);

        TitleLabel.Text = Loc.GetString("circuit-assembly-ui-title");
        RenameButton.Text = Loc.GetString("circuit-assembly-ui-rename");
        TransferButton.Text = Loc.GetString("circuit-assembly-ui-transfer-owner");
        RunButton.Text = Loc.GetString("circuit-assembly-ui-run");
        StopButton.Text = Loc.GetString("circuit-assembly-ui-stop");
        ProgramButton.Text = Loc.GetString("circuit-assembly-ui-program");
        CloseButton.Text = Loc.GetString("circuit-assembly-ui-close");

        RenameButton.OnPressed += _ => SubmitName();
        NameEdit.OnTextEntered += _ => SubmitName();
        TransferButton.OnPressed += _ => OnTransferOwner?.Invoke(OwnerEdit.Text.Trim());
        OwnerEdit.OnTextChanged += _ => UpdateOwnerButton();
        OwnerEdit.OnTextEntered += _ => OnTransferOwner?.Invoke(OwnerEdit.Text.Trim());
        RunButton.OnPressed += _ => OnRun?.Invoke();
        StopButton.OnPressed += _ => OnStop?.Invoke();
        ProgramButton.OnPressed += _ => OnOpenProgram?.Invoke();
        LockButton.OnPressed += _ =>
        {
            if (_lastState != null)
                OnLock?.Invoke(!_lastState.Locked);
        };
        CloseButton.OnPressed += _ => Close();
    }

    private void UpdateOwnerButton()
    {
        TransferButton.Disabled = _lastState?.Locked != false ||
                                  string.IsNullOrWhiteSpace(OwnerEdit.Text);
    }

    private void SubmitName()
    {
        var name = NameEdit.Text.Trim();
        if (name.Length == 0)
            return;

        OnRename?.Invoke(name);
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = DragMode.Move;

        if (Resizable)
        {
            if (relativeMousePos.Y < DragMarginSize)
                mode = DragMode.Top;
            else if (relativeMousePos.Y > Size.Y - DragMarginSize)
                mode = DragMode.Bottom;

            if (relativeMousePos.X < DragMarginSize)
                mode |= DragMode.Left;
            else if (relativeMousePos.X > Size.X - DragMarginSize)
                mode |= DragMode.Right;
        }

        return mode;
    }

    public void Populate(CircuitAssemblyState state)
    {
        _lastState = state;

        if (!_nameInitialized || state.Name != _lastServerName)
        {
            NameEdit.Text = state.Name;
            _nameInitialized = true;
        }

        _lastServerName = state.Name;

        if (!OwnerEdit.HasKeyboardFocus() &&
            (!_ownerInitialized || state.OwnerName != _lastServerOwner))
        {
            OwnerEdit.Text = state.OwnerName ?? string.Empty;
            _ownerInitialized = true;
            _lastServerOwner = state.OwnerName;
        }

        var occupied = 0;
        foreach (var slot in state.Slots)
        {
            if (slot.ItemName != null)
                occupied++;
        }

        StatusLabel.Text = Loc.GetString("circuit-assembly-ui-status",
            ("modules", occupied),
            ("hands", state.Hands),
            ("sensor", state.SensorRange));

        PowerLabel.Text = state.MaxPower > 0
            ? Loc.GetString("circuit-assembly-ui-power",
                ("current", MathF.Round(state.Power)),
                ("max", MathF.Round(state.MaxPower)))
            : Loc.GetString("circuit-assembly-ui-no-power");

        RadioLabel.Text = state.RadioChannels.Count > 0
            ? Loc.GetString("circuit-assembly-ui-radio", ("channels", string.Join(", ", state.RadioChannels)))
            : Loc.GetString("circuit-assembly-ui-no-radio");

        CpuLabel.Text = state.HasCpu
            ? Loc.GetString("circuit-assembly-ui-cpu", ("cpu", state.CpuName ?? "?"))
            : Loc.GetString("circuit-assembly-ui-no-cpu");

        RunningLabel.Text = state.Running
            ? Loc.GetString("circuit-assembly-ui-running")
            : Loc.GetString("circuit-assembly-ui-stopped");

        LockLabel.Text = state.Locked
            ? Loc.GetString("circuit-assembly-ui-locked", ("owner", state.OwnerName ?? "unknown"))
            : Loc.GetString("circuit-assembly-ui-unlocked");
        LockButton.Text = state.Locked
            ? Loc.GetString("circuit-assembly-ui-unlock")
            : Loc.GetString("circuit-assembly-ui-lock");
        var canModify = !state.Locked;
        LockButton.Disabled = false;
        NameEdit.Editable = canModify;
        RenameButton.Disabled = !canModify;
        OwnerEdit.Editable = canModify;
        UpdateOwnerButton();

        ErrorLabel.Text = state.Error ?? string.Empty;
        ErrorLabel.Visible = state.Error != null;

        RunButton.Disabled = !canModify || !state.HasCpu || !state.Powered || state.Running;
        StopButton.Disabled = !canModify || !state.Running;
        ProgramButton.Disabled = !canModify || !state.HasCpu;

        SlotList.Children.Clear();

        foreach (var slot in state.Slots)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 2),
            };

            row.AddChild(new Label
            {
                Text = $"{slot.Role}: {slot.ItemName ?? "-"}",
                HorizontalExpand = true,
            });

            var eject = new Button
            {
                Text = Loc.GetString("circuit-assembly-ui-eject"),
                Disabled = !canModify || slot.ItemName == null,
            };

            var slotId = slot.SlotId;
            eject.OnPressed += _ => OnEject?.Invoke(slotId);
            row.AddChild(eject);
            SlotList.AddChild(row);
        }
    }
}
