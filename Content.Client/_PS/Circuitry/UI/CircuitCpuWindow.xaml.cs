using System;
using System.Linq;
using System.Numerics;
using System.Text;
using Content.Shared._PS.Circuitry;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.Circuitry.UI;

[GenerateTypedNameReferences]
public sealed partial class CircuitCpuWindow : BaseWindow
{
    private const int DragMarginSize = 7;

    public event Action<string>? OnSave;
    public event Action<string>? OnRun;
    public event Action? OnStop;
    public event Action? OnClearLog;

    private string? _lastServerSource;
    private bool _sourceInitialized;
    private bool _dirty;
    private CircuitCpuState? _lastState;

    public CircuitCpuWindow()
    {
        RobustXamlLoader.Load(this);

        TitleLabel.Text = Loc.GetString("circuit-cpu-ui-title");
        SaveButton.Text = Loc.GetString("circuit-cpu-ui-save");
        RevertButton.Text = Loc.GetString("circuit-cpu-ui-revert");
        RunButton.Text = Loc.GetString("circuit-cpu-ui-run");
        StopButton.Text = Loc.GetString("circuit-cpu-ui-stop");
        ClearLogButton.Text = Loc.GetString("circuit-cpu-ui-clear");
        CloseButton.Text = Loc.GetString("circuit-cpu-ui-close");
        ConsoleTitle.Text = Loc.GetString("circuit-cpu-ui-console");

        SaveButton.OnPressed += _ => SubmitSave();
        RevertButton.OnPressed += _ => Revert();
        RunButton.OnPressed += _ => SubmitRun();
        StopButton.OnPressed += _ => OnStop?.Invoke();
        ClearLogButton.OnPressed += _ => OnClearLog?.Invoke();
        CloseButton.OnPressed += _ => Close();

        CodeEditor.TextChanged += _ => OnEditorChanged();
        CodeEditor.SaveRequested += SubmitSave;
        CodeEditor.RunRequested += SubmitRun;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = DragMode.Move;

        if (Resizable)
        {
            if (relativeMousePos.Y < DragMarginSize)
                mode = DragMode.Top;
            else if (relativeMousePos.Y > Size.Y - DragMarginSize)
                mode = DragMode.Bottom;

            if (relativeMousePos.X < DragMarginSize)
                mode |= DragMode.Left;
            else if (relativeMousePos.X > Size.X - DragMarginSize)
                mode |= DragMode.Right;
        }

        return mode;
    }

    public string GetSource()
    {
        return CodeEditor.Text;
    }

    public void Populate(CircuitCpuState state)
    {
        _lastState = state;

        if (state.Source != null &&
            (!_sourceInitialized || LuaCodeEditor.NormalizeText(state.Source) != _lastServerSource))
        {
            CodeEditor.SetText(state.Source);
            _sourceInitialized = true;
            _lastServerSource = CodeEditor.Text;
            _dirty = false;
        }

        var status = state.Running
            ? Loc.GetString("circuit-cpu-ui-running")
            : Loc.GetString("circuit-cpu-ui-stopped");

        if (!state.Installed)
            status += " | " + Loc.GetString("circuit-cpu-ui-not-installed");
        else if (!state.Powered)
            status += " | " + Loc.GetString("circuit-cpu-ui-no-power");

        StatusLabel.Text = Loc.GetString("circuit-cpu-ui-status", ("status", status));
        AssemblyLabel.Text = state.AssemblyName != null
            ? Loc.GetString("circuit-cpu-ui-assembly", ("name", state.AssemblyName))
            : string.Empty;

        ErrorLabel.Text = state.Error ?? string.Empty;
        ErrorLabel.Visible = state.Error != null;

        CodeEditor.Editable = !state.Locked;
        SaveButton.Disabled = state.Locked || !_dirty;
        RevertButton.Disabled = state.Locked || !_dirty;
        RunButton.Disabled = state.Locked || !state.Installed || !state.Powered || state.Running;
        StopButton.Disabled = state.Locked || !state.Running;
        ClearLogButton.Disabled = state.Locked;

        UpdateProgramInfo();
        ConsoleLabel.Text = string.Join("\n", state.Log);
    }

    private void SubmitSave()
    {
        if (SaveButton.Disabled)
            return;

        OnSave?.Invoke(GetSource());
    }

    private void SubmitRun()
    {
        if (RunButton.Disabled)
            return;

        OnRun?.Invoke(GetSource());
    }

    private void OnEditorChanged()
    {
        _dirty = _sourceInitialized && GetSource() != _lastServerSource;
        if (_lastState != null)
        {
            SaveButton.Disabled = _lastState.Locked || !_dirty;
            RevertButton.Disabled = _lastState.Locked || !_dirty;
        }

        UpdateProgramInfo();
    }

    private void Revert()
    {
        if (_lastServerSource == null)
            return;

        CodeEditor.SetText(_lastServerSource);
        _dirty = false;
        SaveButton.Disabled = true;
        RevertButton.Disabled = true;

        UpdateProgramInfo();
    }

    private void UpdateProgramInfo()
    {
        if (_lastState == null)
        {
            ProgramInfoLabel.Text = string.Empty;
            return;
        }

        var source = GetSource();
        var lines = source.Length == 0 ? 0 : source.Count(character => character == '\n') + 1;
        var bytes = Encoding.UTF8.GetByteCount(source);

        var info = Loc.GetString("circuit-cpu-ui-program-info",
            ("lines", lines),
            ("bytes", bytes),
            ("max", _lastState.MaxSourceBytes));

        if (_dirty)
            info += " | " + Loc.GetString("circuit-cpu-ui-unsaved");

        ProgramInfoLabel.Text = info;
    }
}
