using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.Atmos.UI;

/// <summary>
/// Palmtree: client-side UI used to control a temperature pump.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GasTemperaturePumpWindow : FancyWindow
{
    public event Action? ToggleStatusButtonPressed;
    public event Action<float>? HeatTransferRateChanged;

    /// <summary>
    /// Whether the pump is currently switched on, as shown by the toggle button.
    /// </summary>
    public bool PumpEnabled { get; private set; }

    /// <summary>
    /// Highest transfer rate the pump accepts, in percent.
    /// </summary>
    public float MaxRate { get; set; } = 100f;

    public GasTemperaturePumpWindow()
    {
        RobustXamlLoader.Load(this);

        ToggleStatusButton.OnPressed += _ =>
        {
            UpdateStatusButton(!PumpEnabled);
            ToggleStatusButtonPressed?.Invoke();
        };

        RateInput.OnValueChanged += _ => SetRateButton.Disabled = false;

        SetRateButton.OnPressed += _ =>
        {
            RateInput.Value = Math.Clamp(RateInput.Value, 0f, MaxRate);
            HeatTransferRateChanged?.Invoke(RateInput.Value);
            SetRateButton.Disabled = true;
        };

        SetMaxRateButton.OnPressed += _ =>
        {
            RateInput.Value = MaxRate;
            SetRateButton.Disabled = false;
        };

        UpdateStatusButton(false);
    }

    /// <summary>
    /// Updates the on/off button to reflect the pump's state.
    /// </summary>
    public void UpdateStatusButton(bool enabled)
    {
        PumpEnabled = enabled;
        ToggleStatusButton.Text = Loc.GetString(enabled
            ? "gas-temperature-pump-ui-status-on"
            : "gas-temperature-pump-ui-status-off");
    }

    /// <summary>
    /// Sets the transfer rate input field without triggering a change.
    /// </summary>
    public void SetHeatTransferRate(float rate)
    {
        RateInput.Value = rate;
    }

    /// <summary>
    /// Sets the entity displayed in the window.
    /// </summary>
    public void SetEntity(EntityUid entity)
    {
        EntityView.SetEntity(entity);
    }

    /// <summary>
    /// Updates the sensor readouts.
    /// </summary>
    public void UpdateInfo(float inletTemperature, float outletTemperature, float transferredHeat)
    {
        InletTemperatureLabel.Text = float.Round(inletTemperature).ToString();
        OutletTemperatureLabel.Text = float.Round(outletTemperature).ToString();
        TransferredHeatLabel.Text = float.IsNaN(transferredHeat) ? "0" : float.Round(transferredHeat).ToString();
    }
}
