using Content.Client.UserInterface.Controls;
using Content.Shared._PS.Atmos.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.Atmos.UI;

/// <summary>
/// Palmtree: client-side UI used to control a temperature gate.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GasTemperatureGateWindow : FancyWindow
{
    public event Action? ToggleStatusButtonPressed;
    public event Action<float>? TargetTemperatureChanged;
    public event Action<bool>? InvertedChanged;

    /// <summary>
    /// Whether the gate is currently switched on, as shown by the toggle button.
    /// </summary>
    public bool GateEnabled { get; private set; }

    /// <summary>
    /// Highest temperature the target can be set to.
    /// </summary>
    public float MaxTemperature { get; set; } = 4500f;

    public GasTemperatureGateWindow()
    {
        RobustXamlLoader.Load(this);

        ToggleStatusButton.OnPressed += _ =>
        {
            UpdateStatusButton(!GateEnabled);
            ToggleStatusButtonPressed?.Invoke();
        };

        TemperatureInput.OnValueChanged += _ => SetTemperatureButton.Disabled = false;

        SetTemperatureButton.OnPressed += _ =>
        {
            TemperatureInput.Value = Math.Clamp(TemperatureInput.Value, 0f, MaxTemperature);
            TargetTemperatureChanged?.Invoke(TemperatureInput.Value);
            SetTemperatureButton.Disabled = true;
        };

        SetMaxTemperatureButton.OnPressed += _ =>
        {
            TemperatureInput.Value = MaxTemperature;
            SetTemperatureButton.Disabled = false;
        };

        SetToCurrentTemperatureButton.OnPressed += _ =>
        {
            if (InletTemperatureLabel.Text != null &&
                float.TryParse(InletTemperatureLabel.Text, out var inletTemperature))
            {
                TemperatureInput.Value = inletTemperature;
                SetTemperatureButton.Disabled = false;
            }
        };

        Add10Button.OnPressed += _ => AdjustTemperature(10f);
        Add100Button.OnPressed += _ => AdjustTemperature(100f);
        Add1000Button.OnPressed += _ => AdjustTemperature(1000f);
        Subtract10Button.OnPressed += _ => AdjustTemperature(-10f);
        Subtract100Button.OnPressed += _ => AdjustTemperature(-100f);
        Subtract1000Button.OnPressed += _ => AdjustTemperature(-1000f);

        InvertCheckBox.OnPressed += _ => InvertedChanged?.Invoke(InvertCheckBox.Pressed);

        UpdateStatusButton(false);
        return;

        void AdjustTemperature(float adjustment)
        {
            TemperatureInput.Value = Math.Clamp(TemperatureInput.Value + adjustment, 0f, MaxTemperature);
            SetTemperatureButton.Disabled = false;
        }
    }

    /// <summary>
    /// Updates the on/off button to reflect the gate's state.
    /// </summary>
    public void UpdateStatusButton(bool enabled)
    {
        GateEnabled = enabled;
        ToggleStatusButton.Text = Loc.GetString(enabled
            ? "gas-temperature-gate-ui-status-on"
            : "gas-temperature-gate-ui-status-off");
    }

    /// <summary>
    /// Sets the temperature input field without triggering a change.
    /// </summary>
    public void SetTargetTemperature(float temperature)
    {
        TemperatureInput.Value = temperature;
    }

    /// <summary>
    /// Sets the message the invert checkbox shows, without raising <see cref="InvertedChanged"/>.
    /// </summary>
    public void SetInverted(bool inverted)
    {
        InvertCheckBox.Pressed = inverted;
    }

    /// <summary>
    /// Sets the entity displayed in the window.
    /// </summary>
    public void SetEntity(EntityUid entity)
    {
        EntityView.SetEntity(entity);
    }

    /// <summary>
    /// Updates the sensor readouts.
    /// </summary>
    public void UpdateInfo(float inletTemperature, float outletTemperature)
    {
        InletTemperatureLabel.Text = float.Round(inletTemperature).ToString();
        OutletTemperatureLabel.Text = float.Round(outletTemperature).ToString();
    }
}
