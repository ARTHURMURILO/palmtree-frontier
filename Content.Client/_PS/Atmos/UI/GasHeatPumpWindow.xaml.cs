using Content.Client.UserInterface.Controls;
using Content.Shared._PS.Atmos.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._PS.Atmos.UI;

/// <summary>
/// Palmtree: client-side UI used to control a heat pump.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GasHeatPumpWindow : FancyWindow
{
    public event Action? ToggleStatusButtonPressed;
    public event Action<float>? TargetTemperatureChanged;
    public event Action<bool>? SafetiesChanged;

    /// <summary>
    /// Whether the machine is currently switched on, as shown by the toggle button.
    /// </summary>
    public bool PumpEnabled { get; private set; }

    /// <summary>
    /// Highest temperature the target can be set to.
    /// </summary>
    public float MaxTemperature { get; set; } = 593.15f;

    /// <summary>
    /// Lowest temperature the target can be set to.
    /// </summary>
    public float MinTemperature { get; set; } = 73.15f;

    private float _gasTemperature;

    public GasHeatPumpWindow()
    {
        RobustXamlLoader.Load(this);

        ToggleStatusButton.OnPressed += _ =>
        {
            UpdateStatusButton(!PumpEnabled);
            ToggleStatusButtonPressed?.Invoke();
        };

        TemperatureInput.OnValueChanged += _ => SetTemperatureButton.Disabled = false;

        SetTemperatureButton.OnPressed += _ =>
        {
            TemperatureInput.Value = Math.Clamp(TemperatureInput.Value, MinTemperature, MaxTemperature);
            TargetTemperatureChanged?.Invoke(TemperatureInput.Value);
            SetTemperatureButton.Disabled = true;
        };

        SetMaxTemperatureButton.OnPressed += _ =>
        {
            TemperatureInput.Value = MaxTemperature;
            SetTemperatureButton.Disabled = false;
        };

        SetToCurrentTemperatureButton.OnPressed += _ =>
        {
            TemperatureInput.Value = Math.Clamp(_gasTemperature, MinTemperature, MaxTemperature);
            SetTemperatureButton.Disabled = false;
        };

        Add10Button.OnPressed += _ => AdjustTemperature(10f);
        Add100Button.OnPressed += _ => AdjustTemperature(100f);
        Add1000Button.OnPressed += _ => AdjustTemperature(1000f);
        Subtract10Button.OnPressed += _ => AdjustTemperature(-10f);
        Subtract100Button.OnPressed += _ => AdjustTemperature(-100f);
        Subtract1000Button.OnPressed += _ => AdjustTemperature(-1000f);

        SafetiesCheckBox.OnPressed += _ => SafetiesChanged?.Invoke(SafetiesCheckBox.Pressed);

        UpdateStatusButton(false);
        return;

        void AdjustTemperature(float adjustment)
        {
            TemperatureInput.Value = Math.Clamp(TemperatureInput.Value + adjustment, MinTemperature, MaxTemperature);
            SetTemperatureButton.Disabled = false;
        }
    }

    /// <summary>
    /// Updates the on/off button to reflect the machine's state.
    /// </summary>
    public void UpdateStatusButton(bool enabled)
    {
        PumpEnabled = enabled;
        ToggleStatusButton.Text = Loc.GetString(enabled
            ? "gas-heat-pump-ui-status-on"
            : "gas-heat-pump-ui-status-off");
    }

    /// <summary>
    /// Sets the temperature input field without triggering a change.
    /// </summary>
    public void SetTargetTemperature(float temperature)
    {
        TemperatureInput.Value = temperature;
    }

    /// <summary>
    /// Sets the safeties checkbox without raising <see cref="SafetiesChanged"/>.
    /// </summary>
    public void SetSafeties(bool safeties)
    {
        SafetiesCheckBox.Pressed = safeties;
    }

    /// <summary>
    /// Sets the entity displayed in the window.
    /// </summary>
    public void SetEntity(EntityUid entity)
    {
        EntityView.SetEntity(entity);
    }

    /// <summary>
    /// Pushes everything the window shows from the component state.
    /// </summary>
    public void UpdateInfo(
        bool cooling,
        float gasTemperature,
        float gasPressure,
        float wasteTemperature,
        float wastePressure,
        float efficiency,
        float heatMoved)
    {
        _gasTemperature = gasTemperature;

        ModeLabel.Text = Loc.GetString(cooling
            ? "gas-heat-pump-ui-mode-cooling"
            : "gas-heat-pump-ui-mode-heating");

        EfficiencyLabel.Text = Loc.GetString("gas-heat-pump-ui-efficiency",
            ("efficiency", $"{efficiency * 100f:0}"));

        GasTemperatureLabel.Text = float.Round(gasTemperature).ToString();
        GasPressureLabel.Text = float.Round(gasPressure).ToString();
        WasteTemperatureLabel.Text = float.Round(wasteTemperature).ToString();
        WastePressureLabel.Text = float.Round(wastePressure).ToString();

        HeatMovedLabel.Text = MathF.Abs(heatMoved) < 1f
            ? Loc.GetString("gas-heat-pump-ui-idle")
            : Loc.GetString("gas-heat-pump-ui-moving-amount",
                ("amount", $"{MathF.Abs(heatMoved) / 1000f:0.#}"),
                ("direction", Loc.GetString(cooling
                    ? "gas-heat-pump-ui-moving-out"
                    : "gas-heat-pump-ui-moving-in")));

        // Nothing in the waste loop means the heat has nowhere to go.
        var noWaste = cooling && wastePressure < 1f;
        WarningLabel.Visible = noWaste;
        if (noWaste)
            WarningLabel.Text = Loc.GetString("gas-heat-pump-ui-no-waste");
    }
}
